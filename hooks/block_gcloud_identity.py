def _escape_hatch_active() -> bool:
    """ESCAPE_VAR=1 in the hook's OWN process env."""
    return os.environ.get(ESCAPE_VAR, "") == "1"


def main() -> int:
    """Entry point. Reads stdin, decides, emits/logs, returns exit code 0."""
    if _lib.disabled():
        return 0

    try:
        raw = sys.stdin.read()
    except Exception:
        raw = ""

    ev = _lib._parse_event(raw)

    if not ev:
        # Parse error: fail CLOSED only when the raw string mentions gcloud.
        if _raw_mentions_gcloud(raw):
            return _finish(True, "parse-error-with-gcloud-token", raw[:200], cwd_hint=None)
        return 0

    if _lib.tool_name(ev) != "Bash":
        return 0

    command = _lib.bash_command(ev)
    cwd_hint = _lib.cwd(ev)

    block, reason = decision(command)
    return _finish(block, reason, command, cwd_hint=cwd_hint)


def _finish(block: bool, reason: str, command: str, *, cwd_hint: str | None) -> int:
    """Terminal action for a computed decision. Returns exit code (ALWAYS 0).

      BLOCK: log the would-block; honor the OWN-env escape hatch (allow + log);
             if enforcing() emit the canonical deny; else stay silent (log-only).
      ALLOW: nothing emitted.
    """
    if not block:
        return 0

    if reason != "inline-escape-var-forbidden" and _escape_hatch_active():
        _lib.log(HOOK_NAME, "escape-allowed", reason=reason, command=command)
        return 0

    enforce = _lib.enforcing(cwd_hint)
    _lib.log(HOOK_NAME, "would-block", reason=reason, command=command, enforce=enforce)

    if enforce:
        _lib.emit_pretooluse_deny(_message_for(reason, command))
    return 0


def _safe_family_for_command(command: str) -> str | None:
    """`_family_for_command(command)`, but NEVER lets an exception propagate
    out to its caller (P3-3, #5890 round 4 fix round).
    `_family_for_command` already degrades internally to `None` on every
    failure mode it anticipates -- this wrapper exists for the case it
    doesn't: `_message_for`'s deny-message building must NEVER be the thing
    that turns a genuine BLOCK decision into an unhandled exception
    propagating out of `_finish`/`main()` (which already computed `block =
    True` before ever calling `_message_for` -- a crash here would take down
    the whole hook process on a would-block, arguably worse than merely
    losing the per-family hint, since `main()`'s own contract is "always
    exits 0"). `_safe_format_hint(None)` already degrades to the
    scheduler-job fallback example when `family` is None, so every caller
    of this wrapper keeps working (with a possibly-generic hint) rather than
    ever raising."""
    try:
        return _family_for_command(command)
    except Exception:
        return None


