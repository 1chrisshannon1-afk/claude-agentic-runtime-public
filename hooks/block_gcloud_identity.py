def _strip_leading_env_assignments(argv: list[str]) -> list[str]:
    """Drop leading `VAR=value` tokens (an inline env-prefixed invocation,
    e.g. `CLOUDSDK_CORE_ACCOUNT=x gcloud ...`) so the actual program name is
    the first remaining token. Mirrors `_lib.git_segments()`'s own env-prefix
    stripping for git segments (see `_lib.py`'s `_strip_git_globals`/segment
    handling) — gcloud has no shared tokenizer in this codebase, so this is a
    narrow, local re-implementation of just the "leading env assignment"
    piece, not the whole thing.
    """
    _ENV_ASSIGN_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")
    i = 0
    while i < len(argv) and _ENV_ASSIGN_RE.match(argv[i]):
        i += 1
    return argv[i:]


