def _is_safe_format_value(value: str, family: str) -> bool:
    """True iff `value` is a field-PROJECTION format (`yaml(...)`, `json(...)`,
    `table(...)`, `value(...)`, `csv(...)`) whose field list is non-empty and
    every field is an EXACT (case-insensitive) match against `family`'s
    entry in `_SAFE_LEAF_FIELDS` -- an ALLOWLIST of known-safe leaf fields,
    not a "doesn't look unsafe" blocklist (#5890 round 2:
    the prior substring-blocklist design let a PARENT key through, since a
    parent key's own name need not contain any unsafe-looking substring even
    though gcloud prints its entire subtree).

    A bare kind with no parens (`yaml`, `json`, `text`, `table` with no field
    list, `default`, ...) dumps the WHOLE resource and is never safe. An
    empty field list (`table()`), a `.`/`*` wildcard field, or an empty field
    token in a comma-separated list are all always-unsafe regardless of
    family. `value` is expected to be exactly one `kind(...)` projection with
    balanced parentheses and nothing after the closing paren, but a
    concatenated multi-projection value (`table(name) json()`) does NOT fail
    the regex match -- ROUND 2 CORRECTION (D1): an earlier version of this
    docstring claimed otherwise. `_FORMAT_PROJECTION_RE`'s `.*` is greedy, so
    it matches through to the LAST closing paren, yielding
    `fields="name) json("`. What denies this shape is the per-field
    allowlist loop below: that malformed single field-token is never an
    exact match against any family's allowlist, so it is denied there
    regardless of which family is passed. Never raises: any unexpected shape
    returns False (fail toward denying, the safe direction for a secret-leak
    gate).
    """
    try:
        value = (value or "").strip()
        if not value:
            return False
        m = _FORMAT_PROJECTION_RE.match(value)
        if not m:
            return False
        fields_raw = m.group("fields").strip()
        if not fields_raw:
            return False
        allowlist = _SAFE_LEAF_FIELDS.get(family)
        if not allowlist:
            return False
        for field in fields_raw.split(","):
            field = field.strip()
            if field in _ALWAYS_UNSAFE_FIELD_TOKENS:
                return False
            if "." in field or "*" in field:
                # A dotted/bracketed path or wildcard not already covered by
                # an exact allowlist entry (the allowlists above DO include a
                # handful of dotted leaf paths verbatim, e.g.
                # "httptarget.httpmethod" -- those match via the plain
                # membership check below since they're literal allowlist
                # entries, not a pattern). Anything else with a `.`/`*` that
                # isn't a literal allowlisted entry is denied here rather
                # than guessed at.
                if '"' in field:
                    # A quoted key (an annotation name) is matched by gcloud
                    # case-SENSITIVELY, so lowercasing here would let a
                    # case-variant spelling of an allowed key print a
                    # different annotation (#5936 item 2, trust-architect
                    # finding 1). Exact match only; any other casing denies.
                    if field not in allowlist:
                        return False
                    continue
                if field.lower() not in allowlist:
                    return False
                continue
            if field.lower() not in allowlist:
                return False
        return True
    except Exception:
        return False


