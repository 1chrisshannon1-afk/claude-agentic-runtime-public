# authorize a wildcard by containing a literal "." or "*" entry.
_ALWAYS_UNSAFE_FIELD_TOKENS = frozenset({".", "*", ""})


def _format_value(rest: list[str]) -> tuple[str | None, bool, bool]:
    """The `--format` value for this gcloud invocation, whether the flag was
    present at all, and whether MULTIPLE `--format` tokens were seen.

    Returns (value_or_None, present, multiple):
      * `present=False` means no `--format` token appeared anywhere in `rest`
        (gcloud's own default output for `describe` applies, a full dump);
      * `value` is the LAST `--format` token's value -- NOT the first, which
        is the exact B2 bug this replaces (the gate used to read the first
        token while gcloud itself applies the last). ROUND 2 CORRECTION
        (D1): an earlier version of this docstring attributed "the rightmost
        format ... takes precedence" to `gcloud topic formats`. That text is
        not in the topic help; it is a code comment in the SDK's own
        `calliope/display.py`, describing how a single, already-combined
        format STRING resolves internally, not gcloud's CLI flag-repetition
        behavior. The rule this function actually relies on -- that
        repeating `--format` on one command line makes the LAST occurrence
        win -- is argparse's own last-value-wins behavior for a flag with no
        `action="append"` (verified in round 1 against the SDK's own arg
        parser wiring; gcloud does not override this default for `--format`);
      * `multiple=True` means 2+ distinct `--format` tokens appeared. The
        caller treats `multiple` as an unconditional deny on its own,
        regardless of what the last value looks like: a *single* `--format`
        VALUE can itself concatenate more than one projection
        (`table(name) json()`, see `_is_safe_format_value`'s own docstring
        for exactly how that shape is denied), so seeing 2+ tokens is already
        proof this invocation's real behavior cannot be soundly reasoned
        about from one parsed value.
      * `value=None` with `present=True` cannot happen (a value-less
        `--format` at the end of the command is not a valid gcloud
        invocation) -- this function still returns `("", True, ...)` in that
        malformed case, which `_is_safe_format_value` correctly treats as
        unsafe rather than raising.

    Scans the ENTIRE token list positionally (never stops at the first
    match), mirroring `_evaluate_gcloud_argv`'s own path walk — `--format`
    may appear before OR after the subcommand path, exactly like every other
    global flag this module already handles.
    """
    values: list[str] = []
    for i, tok in enumerate(rest):
        if tok.startswith("--format="):
            values.append(tok[len("--format=") :])
        elif tok == "--format":
            if i + 1 < len(rest):
                values.append(rest[i + 1])
            else:
                values.append("")
    if not values:
        return (None, False, False)
    return (values[-1], True, len(values) > 1)


