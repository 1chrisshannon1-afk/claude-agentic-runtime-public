def _is_plausible_run_group_prefix(path: tuple[str, ...]) -> bool:
    """True iff `path` (a `run`-starting path-reading-in-progress -- see the
    ROUND 8 correction below for what "starting" actually means here) could
    STILL become a prefix match for at least one `run`-starting describe/list
    verb group as MORE tokens are appended to it (ROUND 7, B1-r6).

    This is the key fix for B1-r6: the round-6 walk only ever stopped
    branching a path once it hit the fixed `_MAX_PATH_ELEMENTS` length cap
    or ran out of input tokens -- so an ORDINARY, non-describe/list `run`
    command (`run services update`, `run jobs execute`, ...) still branched
    on every one of its many real, legitimate flags, each contributing
    non-flag VALUE tokens to `path` that could never possibly turn it into a
    `services describe`/`jobs list`/etc. shape, purely because nothing
    stopped the walk from continuing to grow a path that had ALREADY proven
    it could never match anything. `run services update` itself diverges
    from every covered group at index 2 (`update` != `describe`/`list`) --
    once that divergence is known, appending MORE tokens (real update flags'
    own values) can never make it start matching again, since a verb-group
    check is always an EXACT-PREFIX match (`variant[:n] == list(group)`),
    never a substring or suffix match.

    ROUND 8 CORRECTION (B1-r7, a REGRESSION this function's own round-7
    docstring caused): the prior text here claimed `path` arrives "already
    stripped of any leading alpha/beta element" -- that was never true of
    the ACTUAL caller (`_gcloud_command_path_variants`'s branching walk),
    which builds `path` directly from `rest = argv[1:]` with NO alpha/beta
    stripping anywhere in that walk (stripping only ever happened on
    `base_path`, a completely separate reading computed by
    `_gcloud_command_path`). So for `gcloud beta run services --region
    us-central1 describe svc`, this function was called with `path =
    ("beta",)` on the very first token -- `"beta"` matches NO
    `_RUN_DESCRIBE_LIST_GROUPS` entry at index 0 (every one of them starts
    with the literal `"run"`), so the branch was judged implausible and
    finished IMMEDIATELY, before `run`/`services`/`describe` were ever
    consumed -- silently ALLOWING `beta`/`alpha`-prefixed group-flag
    describes that the non-prefixed form correctly denies (confirmed:
    `gcloud beta/alpha run services/jobs --region ... describe ...` all
    wrongly allowed pre-fix, an actual regression from round 6, which
    stripped the track prefix in its own single-reading walk and had no
    such gap).

    Fixed by stripping a single leading `alpha`/`beta` element from `path`
    itself, INSIDE this function, before running the positional check --
    this makes the function's own contract self-sufficient (true regardless
    of whether a future caller remembers to strip it first) rather than
    relying on an external precondition the ACTUAL branching walk never
    honored. `_MAX_PATH_ELEMENTS` (6) still comfortably fits a
    track-prefixed path: the longest covered group is 5 elements, plus the
    stripped `alpha`/`beta` token itself is one more, and the branching
    walk's own length cap is checked against the UNSTRIPPED `path` (so an
    `alpha`/`beta`-prefixed reading gets one extra element of headroom
    before the length cap trips, exactly matching how much longer its own
    real path legitimately is).

    For each index `k` in `range(len(chk))` (the alpha/beta-stripped
    working copy), this checks whether ANY covered group has `group[k] ==
    chk[k]` (a group shorter than `chk` cannot match at an index beyond its
    own length, so it drops out of consideration once `chk` grows past it
    -- handled by the `k < len(group)` guard). `chk` is plausible iff, for
    EVERY index `k`, at least one covered group still agrees with it at
    that index (a group's own agreement can come from a DIFFERENT group at
    each index -- this checks positional feasibility against the WHOLE
    covered set, not against one single candidate group at a time, since
    different branches of the walk may still be tracking different real
    candidate groups).

    Never raises: any internal error returns True (fail toward CONTINUING to
    branch rather than prematurely truncating a path that might still be a
    real describe/list -- the failure direction that keeps this function's
    bug surface on the SAFE side of B1's original fail-closed contract; a
    bug here can at worst reintroduce some of B1's original over-branching,
    never silently miss a real describe/list match)."""
    try:
        chk = path[1:] if path[:1] in (("alpha",), ("beta",)) else path
        n = len(chk)
        if n == 0:
            return True
        for k in range(n):
            token = chk[k]
            if not any(
                k < len(group) and group[k] == token for group in _RUN_DESCRIBE_LIST_GROUPS
            ):
                return False
        return True
    except Exception:
        return True

# B1 bounds (#5890 round 6) for
# `_gcloud_command_path_variants`'s branching walk -- see that function's own
# comment for the full reasoning. No verb group in `_DESCRIBE_VERB_GROUPS`/
# `_LIST_VERB_GROUPS` is longer than 5 elements (`run jobs executions tasks
# describe`); one extra element of margin.
_MAX_PATH_ELEMENTS = 6
# A hard ceiling on the number of distinct completed path readings this
# module will ever enumerate for one command. Chosen well above any
# realistic legitimate command (a handful of unrecognized flags produces a
# handful of variants) but small enough that hitting it is itself proof the
# command is not one this module can soundly reason about.
_MAX_PATH_VARIANTS = 64
# Sentinel path returned (alongside `base_path`) when the branching walk
# exceeds `_MAX_PATH_VARIANTS` -- deliberately NOT a real gcloud path (no
# verb group can ever match it), so its ONLY effect is to signal "this
# command's true path is ambiguous beyond what this module will enumerate"
# to callers that specifically check for it (`_evaluate_gcloud_argv`,
# `_family_for_command`), never a silent extra allow/deny path by accident.
_TOO_MANY_VARIANTS_SENTINEL: tuple[str, ...] = ("\x00too-many-path-variants",)


def _gcloud_command_path_variants(argv: list[str]) -> list[list[str]]:
    """Every DISTINCT subcommand-path reading of `argv` a real gcloud parse
    could produce (B1, #5890 round 4 fix round).

    `_gcloud_command_path` (above) computes exactly ONE reading: every
    unrecognized flag token is treated as taking NO value. That reading is
    exact for every verb group this module checks EXCEPT `run` (see
    `_RUN_GROUP_VALUE_FLAGS`'s sourcing comment) -- `run services`/`run
    jobs`/`run revisions` each declare additional value-taking flags
    (`--region`, `--platform`, `--cluster`, `--cluster-location`,
    `--context`, `--kubeconfig`) at the GROUP level, which this module's
    fixed `_GLOBAL_VALUE_FLAGS` allowlist does not and must not include
    (they are not valid on every gcloud command, only on `run`'s own
    subtree). When gcloud sees one of those tokens before the verb, it
    consumes the NEXT token as that flag's value -- exactly like a global
    value flag -- so treating it as a no-value flag misreads the value token
    as the next PATH element instead, truncating/shifting the path and
    letting an unmasked `describe`/`list` slip through unmatched (the B1
    bypass: `gcloud run services --region us-central1 describe svc` reads as
    path `["services", "us-central1", "describe", "svc"]` under the
    single-reading walk, which matches no `_DESCRIBE_VERB_GROUPS` entry).

    Rather than trying to special-case one exact grammar for `run` (its own
    flags parser resolves this correctly, but duplicating that resolution
    here would need to track gcloud's own argparse behavior indefinitely),
    this returns EVERY distinct path obtained by walking the argv once and,
    at each UNRECOGNIZED space-separated flag token (the same "unknown flag"
    case `_gcloud_command_path` treats as a bare no-value skip), branching
    into BOTH interpretations: (a) no-value (skip one token, matching
    `_gcloud_command_path`'s existing behavior) and (b) value-consuming (skip
    two tokens, treating the next token as this flag's value). The caller
    (`_evaluate_gcloud_argv`) checks EVERY returned path against the verb
    groups and blocks if ANY of them matches -- fail-closed on the
    interpretation, never fail-open, exactly matching this module's stated
    contract that an unrecognized/ambiguous shape is treated as the more
    dangerous reading, not the more permissive one.

    Scoped to commands whose PATH ITSELF starts with `run` under the
    default (no-value) reading -- computed by calling
    `_gcloud_command_path(argv)` first and checking its own first element,
    since a group-level flag can only ever apply to a family that HAS one
    (`_GROUPS_WITH_GROUP_LEVEL_FLAGS`). This mirrors the sourcing comment's
    own finding: `scheduler`/`functions` have no group-level flags at all,
    so branching for them would only ever produce byte-identical duplicate
    paths -- correct but wasted work. Note this scoping check itself uses
    the SAME (a) no-value reading being branched from, so it is exactly as
    exposed to the ambiguity as the thing it's guarding; that's fine here,
    since the branch below re-derives the alternate reading with its own
    independent walk rather than trusting the scoping check's specific
    token-count, and a false-negative scoping miss (this check reading `run`
    when the flag-consuming reading would NOT have started with `run`) is
    not a real shape: only a value token immediately after an unrecognized
    flag can ever shift what element lands first, and `run` is always
    argv[1] verbatim regardless of which reading is used for LATER tokens.

    Always includes the single-reading path first (identical to
    `_gcloud_command_path(argv)`), then any additional distinct variants.
    Never raises: any internal error degrades to returning just the single
    reading (delegating to `_gcloud_command_path`, which itself never
    raises), so a bug here can only narrow coverage back to the pre-B1-fix
    single reading, never crash the hook.
    """
    try:
        base_path = _gcloud_command_path(argv)
        if not base_path or base_path[0] not in _GROUPS_WITH_GROUP_LEVEL_FLAGS:
            return [base_path]

        rest = argv[1:]
        # Re-walk `rest` exactly like `_gcloud_command_path`, but at each
        # UNRECOGNIZED flag token, branch: append one path-building step
        # under BOTH the no-value and value-consuming readings. Each
        # element of `frontier` is (index_into_rest, path_so_far).
        #
        # B1 fix (#5890 round 6): the branch above has no
        # inherent bound -- each unrecognized flag DOUBLES the frontier, so a
        # command padded with N unrecognized flags produces up to 2**N
        # (index, path) states, none of them de-duplicated until the walk
        # finished. Measured pre-fix: a `run` command with 22 unrecognized
        # `--flag value` pairs took ~10s; ~44 would mean roughly 10 minutes
        # of CPU and gigabytes of memory in one hook call -- and if the
        # harness ever treats a hook timeout as non-blocking (unverified,
        # deliberately not relied on), that turns a deny into an allow. Two
        # independent, always-active bounds close this, chosen to match this
        # module's own "when in doubt, fail closed with a bounded rule, not
        # cleverer parsing" design directive:
        #
        #   1. PATH-LENGTH CAP (`_MAX_PATH_ELEMENTS`): no `_DESCRIBE_VERB_GROUPS`/
        #      `_LIST_VERB_GROUPS` entry is longer than 5 path elements (the
        #      longest, `run jobs executions tasks describe`, has exactly 5).
        #      Once a branch's own `path` reaches `_MAX_PATH_ELEMENTS`
        #      elements, it can never newly START matching a verb group it
        #      wasn't already matching at a shorter prefix (a verb-group
        #      check is always a PREFIX match, `variant[:n] == list(group)`),
        #      so appending further real path tokens to that branch can only
        #      ever reproduce a prefix already covered. That branch is
        #      finished immediately (its current `path`, truncated to the
        #      cap, is completed) rather than continuing to consume tokens --
        #      collapsing what would otherwise be an unbounded tail of
        #      per-token branch points into one completed state per branch
        #      that reaches the cap.
        #   2. STATE MEMOIZATION: `(i, tuple(path))` is the full state a
        #      frontier entry carries. Two different branch orders can reach
        #      the IDENTICAL `(i, path)` state (e.g. two unrelated
        #      unrecognized flags earlier in the walk, resolved in either
        #      order, that happen to consume the same total token count by
        #      the time `i` is reached) -- memoizing collapses those
        #      duplicate sub-walks instead of re-exploring them.
        #   3. VARIANT-COUNT CAP (`_MAX_PATH_VARIANTS`): a hard ceiling on the
        #      total number of DISTINCT completed paths this function will
        #      ever return. This is not merely a performance bound -- once
        #      the ceiling is hit, this function stops trying to enumerate
        #      every remaining reading and instead reports the command as
        #      genuinely ambiguous via `_TOO_MANY_VARIANTS` sentinel; the
        #      caller (`_evaluate_gcloud_argv`) treats that sentinel as a
        #      covered-family ambiguity and fails CLOSED for it (never a
        #      silent allow, and never an unbounded loop) -- matching this
        #      module's fail-closed posture on every other parse ambiguity,
        #      per the round-6 design directive: "on exceeding it, treat the
        #      command as ambiguous and fail closed only if it's a covered
        #      family, never a timeout."
        #
        # All three bounds are small, fixed constants -- no loop or
        # recursion in this function can run longer than a small constant
        # number of steps regardless of `rest`'s length or flag count.
        # ROUND 7 (B1-r6): a FOURTH bound, on top of the three above -- STOP
        # BRANCHING a path the instant it is no longer a plausible prefix of
        # ANY covered `run` describe/list group (`_is_plausible_run_group_
        # prefix`). Round 6's three bounds (path-length cap, memoization,
        # variant-count ceiling) closed the exponential-time hole but left a
        # DIFFERENT, correctness-affecting gap: an ORDINARY `run services
        # update api --region us-central1 --memory 1Gi --cpu 2 ...` (a
        # perfectly normal, safe command with many real, documented flags)
        # still branched on every one of its unrecognized flags, because
        # nothing stopped the walk once `path` had ALREADY diverged from
        # every covered group (`update` is never `describe`/`list`). With
        # enough real flags, this alone pushed the variant COUNT past
        # `_MAX_PATH_VARIANTS`, and `_evaluate_gcloud_argv`'s own
        # `run-path-too-ambiguous` sentinel handling then denied the command
        # outright -- a real regression the round-6 fix round's own docs and
        # tests never caught (they exercised the sentinel path only with
        # commands whose SECOND path element genuinely was a covered
        # keyword). This bound closes it at the source: once `path` is no
        # longer plausible, THIS branch is finished immediately (its current
        # `path` is recorded and no further tokens are consumed from it) --
        # it can never retroactively become a describe/list match by
        # consuming more real flag values, so there is nothing further to
        # explore down this branch. Real `run services update`/`run jobs
        # execute`/etc. commands therefore produce only a HANDFUL of
        # variants (bounded by how many unrecognized flags appear BEFORE the
        # path diverges, typically 0-2), never one that scales with the
        # command's total flag count.
        frontier: list[tuple[int, tuple[str, ...]]] = [(0, ())]
        completed: set[tuple[str, ...]] = set()
        visited: set[tuple[int, tuple[str, ...]]] = set()
        n = len(rest)
        truncated = False
        while frontier:
            if len(completed) > _MAX_PATH_VARIANTS:
                truncated = True
                break
            i, path = frontier.pop()
            if (i, path) in visited:
                continue
            visited.add((i, path))
            if not _is_plausible_run_group_prefix(path):
                completed.add(path)
                continue
            if len(path) >= _MAX_PATH_ELEMENTS:
                completed.add(path)
                continue
            if i >= n:
                completed.add(path)
                continue
            tok = rest[i]
            if not tok.startswith("-"):
                frontier.append((i + 1, path + (tok,)))
                continue
            if "=" in tok or tok in _GLOBAL_BOOLEAN_SHORT_FLAGS:
                frontier.append((i + 1, path))
                continue
            name = tok[2:] if tok.startswith("--") else tok[1:]
            if tok.startswith("--") and name in _GLOBAL_BOOLEAN_FLAGS:
                frontier.append((i + 1, path))
                continue
            if tok.startswith("--") and name in _GLOBAL_VALUE_FLAGS:
                frontier.append((i + 2, path))
                continue
            if tok.startswith("--") and name in _RUN_GROUP_VALUE_FLAGS:
                # A KNOWN group-level value flag: gcloud always consumes the
                # next token as its value here -- only ONE reading is real,
                # so no branch (this is not the ambiguous case; it's the
                # documented fix for it).
                frontier.append((i + 2, path))
                continue
            # An unrecognized flag -- the genuinely ambiguous case. Branch
            # into both readings so the caller can check both against the
            # verb groups.
            frontier.append((i + 1, path))  # (a) no-value
            frontier.append((i + 2, path))  # (b) value-consuming

        if truncated:
            return [base_path, list(_TOO_MANY_VARIANTS_SENTINEL)]

        # B1 (round 6): `base_path` comes from `_gcloud_command_path`, which
        # has NO length cap of its own (it walks the FULL `rest`, by design
        # -- it is also used standalone, e.g. by `_family_for_path`, where
        # an uncapped path is correct). Without capping it HERE too, this
        # function's own returned "single-reading" entry could still be
        # arbitrarily long for a command with many unrecognized flags each
        # followed by a bare (non-flag) value token under the SAME no-value
        # reading the branching walk above already caps -- reintroducing an
        # unbounded element into an otherwise-bounded return value. Capping
        # is SAFE for every caller: every verb-group check is a PREFIX match
        # (`variant[:n] == list(group)`), so truncating never changes
        # whether a real group matches, and `_family_for_path` receives the
        # capped SAME-SHAPE path this function already returns for its own
        # variants.
        base_path_capped = base_path[:_MAX_PATH_ELEMENTS]

        out: list[list[str]] = []
        seen: set[tuple[str, ...]] = set()
        for path_tuple in completed:
            path = list(path_tuple)
            if path[:1] in (["alpha"], ["beta"]):
                path = path[1:]
            key = tuple(path)
            if key in seen:
                continue
            seen.add(key)
            out.append(path)
        if not out:
            return [base_path_capped]
        # Ensure the single-reading path is present and first, matching this
        # function's documented ordering guarantee (callers that only need
        # backward-compatible behavior can safely take `variants[0]`).
        if base_path_capped in out:
            out.remove(base_path_capped)
        return [base_path_capped] + out
    except Exception:
        try:
            return [_gcloud_command_path(argv)]
        except Exception:
            return [[]]


_DESCRIBE_LIST_FAMILY_REASONS = frozenset(
    {
        "describe-unmasked-format",
        "list-unmasked-format",
        "describe-multiple-format",
        "list-multiple-format",
        "describe-flags-file",
        "list-flags-file",
    }
)


def _family_for_path(path: list[str]) -> str | None:
    """Which `_SAFE_LEAF_FIELDS` family (if any) a gcloud subcommand PATH
    (already env-prefix-stripped, release-track-stripped — the same shape
    `_gcloud_command_path` returns) matches, checking `_DESCRIBE_VERB_GROUPS`
    then `_LIST_VERB_GROUPS` in that order, exactly like
    `_evaluate_gcloud_argv`'s own dispatch. Factored out of
    `_family_for_command` so both that function and any future caller share
    one verb-group walk rather than duplicating it. Never raises (path
    membership checks only)."""
    for group, family in _DESCRIBE_VERB_GROUPS:
        n = len(group)
        if path[:n] == list(group):
            return family
    for group, family in _LIST_VERB_GROUPS:
        n = len(group)
        if path[:n] == list(group):
            return family
    return None


def _family_for_command(command: str, depth: int = 0) -> str | None:
    """Re-derivation of the `_SAFE_LEAF_FIELDS` family for the SEGMENT (or
    NESTED TEXT, round 6) that actually BLOCKED `command` under
    `decision()`, for building a per-family deny-message hint
    (#5890 round 2, B6; round 3 fix round, item 3; round 6,
    P2-3). `decision()`'s own contract is `(block, reason) -> tuple[bool,
    str]` — unchanged here, matching every sibling gate — so the family is
    not threaded through that return value; instead `_message_for` re-parses
    the ORIGINAL command text it already has in scope, using the exact same
    segment walk + `_evaluate_gcloud_argv` dispatch `decision()` itself used
    to reach its answer.

    ROUND 3 CORRECTION (item 3): an earlier version of this function (and
    this docstring) returned the family of the FIRST segment that matched
    ANY describe/list verb group, regardless of whether that segment was the
    one `decision()` actually blocked on -- for a compound command like
    `gcloud scheduler jobs list --format='value(name)' && gcloud run
    services describe s` (the scheduler `list` is SAFE; the `run services
    describe` is what blocks), that returned `scheduler-job`, the WRONG
    family, silently mismatched against the `describe-unmasked-format`
    reason the deny message was actually built for. This function now
    mirrors `decision()`'s own "first BLOCKING segment wins" semantics
    exactly: it re-evaluates each gcloud segment with `_evaluate_gcloud_argv`
    (the identical function `decision()` calls) and returns the family of
    the first segment whose reason is one of the describe/list-family
    reasons (`_DESCRIBE_LIST_FAMILY_REASONS`) -- i.e. the SAME segment
    `decision()` stopped on, not merely the first one that happens to name a
    covered verb group.

    ROUND 6 CORRECTION (P2-3): `_gcloud_segments` (this function's prior
    sole source of segments) only ever splits TOP-LEVEL command segments --
    it has no notion of `bash -c`/`eval`/heredoc/`$(...)`/backtick nested
    text at all, unlike `decision()`'s own `_decision_segments_and_nested`,
    which recurses into all of them. So for a command `decision()` blocked
    ONLY because of a gcloud invocation hidden in nested text (`do gcloud
    run jobs --region r describe j` -- a group-level flag shape reached via
    a leading shell keyword `_gcloud_segments` handles fine at the TOP
    level, but `bash -c 'gcloud run services describe s'` needs the nested
    extraction this function never performed), this function found no
    matching segment at all and returned None -- silently falling back to
    the generic `scheduler-job` hint, which then denies AGAIN when followed,
    exactly the failure round 3's own fix (item 3, above) closed for
    top-level segments but never extended to nested text.

    Fixed by mirroring `_decision_segments_and_nested`'s own recursion
    shape: after checking this command's own top-level segments (via
    `_gcloud_segments`, unchanged), extract every `bash -c`/`eval`/
    here-string body, `$(...)`/backtick command-substitution span, and
    shell-interpreter-fed heredoc body found anywhere in `command` (the
    SAME extractors `_decision_segments_and_nested` uses:
    `_extract_dash_c_body`, `_extract_eval_body`, `_extract_here_string_body`,
    `_extract_command_substitutions`, `_extract_shell_heredoc_bodies`), and
    recurse into each with this SAME function, depth-capped identically to
    `_decision_segments_and_nested` (`_MAX_NESTED_EXTRACTION_DEPTH`) so this
    function can never loop or recurse longer than that shared bound allows.
    Top-level segments are still checked FIRST and nested text only when no
    top-level segment itself resolves a family, mirroring `decision()`'s own
    "first blocking thing wins" precedence (a top-level segment can only ever
    be `decision()`'s actual blocking point before any nested text is even
    examined, by construction of `_decision_segments_and_nested`'s own
    control flow).

    An earlier draft of this docstring also claimed "Returns None on ...
    multiple gcloud segments" -- that was never true of the code (a
    multi-segment command was never special-cased to return None; the old
    code just happened to return the first VERB-GROUP MATCH's family
    regardless of segment count, which is a different and wrong claim). This
    function returns None only on parse failure, exhausted recursion depth,
    or when no segment's/nested text's evaluation matches a describe/
    list-family reason.

    Never raises."""
    try:
        segments = _gcloud_segments(command)
    except Exception:
        segments = []
    for seg_argv, untokenizable in segments:
        if untokenizable or not seg_argv:
            continue
        try:
            block, reason = _evaluate_gcloud_argv(seg_argv)
        except Exception:
            continue
        if not block or reason not in _DESCRIBE_LIST_FAMILY_REASONS:
            continue
        # P2-2: `_evaluate_gcloud_argv` now checks EVERY gcloud-token-
        # starting slice in `seg_argv`, not just the first -- re-derive
        # which slice actually matched by re-running the same search this
        # function's own B1 path-variant walk needs to operate on, so the
        # family lookup below uses the SAME slice `_evaluate_gcloud_argv`
        # blocked on, not always the first. (P3-a, round 7: this call site
        # is a HINT-building lookup, not a block/allow decision -- it does
        # not need `_evaluate_gcloud_argv`'s own truncation-fails-closed
        # handling; a truncated scan here just means a possibly-incomplete
        # slice list, which `candidate_slices`'s own fallback already
        # degrades gracefully from, same as an empty result.)
        try:
            gcloud_slices, _slices_truncated = _find_all_gcloud_argv_slices(seg_argv)
        except Exception:
            gcloud_slices = []
        candidate_slices = gcloud_slices or [seg_argv]
        for gcloud_argv in candidate_slices:
            try:
                slice_block, slice_reason = _evaluate_one_gcloud_slice(gcloud_argv)
            except Exception:
                continue
            if not slice_block or slice_reason not in _DESCRIBE_LIST_FAMILY_REASONS:
                continue
            argv = _strip_leading_env_assignments(gcloud_argv)
            # B1: try every path reading (not just the single-reading
            # `path`), since `_evaluate_one_gcloud_slice` may have matched
            # under the value-consuming reading of a `run` group-level
            # flag -- using only the single reading here would silently
            # fail to find ANY matching family for exactly the commands B1
            # fixed, falling through to the generic fallback hint instead
            # of the correct per-family one.
            try:
                variants = _gcloud_command_path_variants(argv)
            except Exception:
                variants = [_gcloud_command_path(argv)]
            for path in variants:
                family = _family_for_path(path)
                if family is not None:
                    return family

    # P2-3 (round 6): no top-level segment resolved a family -- recurse into
    # nested text exactly like `_decision_segments_and_nested` does, so a
    # gcloud invocation hidden inside a `bash -c`/`eval`/here-string/
    # `$(...)`/backtick/heredoc-fed-to-an-interpreter body still gets a real
    # per-family hint instead of silently falling back to the generic one.
    if depth > _MAX_NESTED_EXTRACTION_DEPTH:
        return None

    try:
        command_mentions_gcloud_text = bool(_GCLOUD_WORD_RE.search(command))
    except Exception:
        command_mentions_gcloud_text = True
    if not command_mentions_gcloud_text:
        return None

    nested_texts: list[str] = []
    try:
        raw_segments = _lib._split_segments(command)
    except Exception:
        raw_segments = []
    for seg in raw_segments:
        try:
            seg_argv = shlex.split(seg)
        except Exception:
            continue
        dash_c = _extract_dash_c_body(seg_argv)
        if dash_c is not None:
            nested_texts.append(dash_c)
        eval_body = _extract_eval_body(seg_argv)
        if eval_body is not None:
            nested_texts.append(eval_body)
        here_string = _extract_here_string_body(seg_argv)
        if here_string is not None:
            nested_texts.append(here_string)

    try:
        subs, subs_ambiguous = _extract_command_substitutions(command)
    except Exception:
        subs, subs_ambiguous = ([], True)
    if not subs_ambiguous:
        nested_texts.extend(subs)

    try:
        heredocs, heredocs_ambiguous = _extract_shell_heredoc_bodies(command)
    except Exception:
        heredocs, heredocs_ambiguous = ([], True)
    if not heredocs_ambiguous:
        nested_texts.extend(heredocs)

    for text in nested_texts:
        if not text or not text.strip():
            continue
        family = _family_for_command(text, depth + 1)
        if family is not None:
            return family

    return None


def _evaluate_gcloud_argv(raw_argv: list[str]) -> tuple[bool, str]:
    """Given one shlex-split argv for a single command segment, return
    (block, reason) -- fail CLOSED across EVERY gcloud-token-starting slice
    in `raw_argv`, not merely the first one (ROUND 6, P2-2).

    ROUND 6 CORRECTION (P2-2): the prior version of this function evaluated
    only `_find_gcloud_argv(raw_argv)`'s single, FIRST-MATCH slice. That
    missed a real gcloud invocation entirely when an EARLIER argument merely
    happened to end in `/gcloud` as a path or flag value, not a program
    invocation -- `docker run -v ~/.config/gcloud:/root/.config/gcloud IMAGE
    gcloud run services describe s` (a Docker volume-mount argument) and
    `sudo --preserve-env=/x/gcloud gcloud config set account x` (a sudo flag
    value) both silently allowed the REAL gcloud command that followed,
    since `_find_gcloud_argv` returned only the first, irrelevant match. See
    `_find_all_gcloud_argv_slices`'s own docstring for the full reasoning.

    Now delegates the actual per-slice evaluation to
    `_evaluate_one_gcloud_slice` (the unchanged former body of this
    function) and calls it once per DISTINCT slice
    `_find_all_gcloud_argv_slices` finds (capped at `_MAX_GCLOUD_SLICES`),
    returning the FIRST slice's blocking verdict -- fail closed on the
    interpretation: if ANY slice is a real, dangerous gcloud invocation,
    this command is treated as one, exactly matching this module's B1
    "never trust the more permissive reading" posture.

    ROUND 7 (P3-a): `_find_all_gcloud_argv_slices` now also reports whether
    its own scan was truncated by the slice cap before it finished looking
    at all of `raw_argv` -- when it was, this function denies outright
    (`untokenizable-segment-with-gcloud`) rather than evaluating only the
    partial slice list as if it were the complete answer. See that
    function's own docstring for the repro this closes.

    Never raises (each per-slice call has its own try/except via
    `_evaluate_one_gcloud_slice`; this wrapper's own slice-finding call is
    independently guarded by `_find_all_gcloud_argv_slices`'s own
    never-raises contract)."""
    try:
        slices, truncated = _find_all_gcloud_argv_slices(raw_argv)
    except Exception:
        slices, truncated = [], True
    if truncated:
        return (True, "untokenizable-segment-with-gcloud")
    if not slices:
        return (False, "")
    for gcloud_argv in slices:
        block, reason = _evaluate_one_gcloud_slice(gcloud_argv)
        if block:
            return (block, reason)
    return (False, "")


def _evaluate_one_gcloud_slice(gcloud_argv: list[str]) -> tuple[bool, str]:
    """The per-slice evaluation core of `_evaluate_gcloud_argv` (ROUND 6,
    P2-2 -- factored out so the wrapper above can call it once per
    gcloud-token-starting slice in a segment's argv, never duplicating this
    dispatch logic). `gcloud_argv` is ALREADY the gcloud invocation's own
    argv slice (starting at the `gcloud` token itself) -- callers other than
    `_evaluate_gcloud_argv` should not call this directly unless they have
    already located that slice themselves.
    """
    # ---- --log-http -- applies to EVERY gcloud verb, checked FIRST and
    # before any verb-specific dispatch below (#5890
    # round 2, B3): `--log-http` prints the full API response body to stderr
    # regardless of what `--format` was requested -- `gcloud scheduler jobs
    # describe j --format='value(name)' --log-http` would otherwise pass the
    # masked-format check below while still leaking the unmasked response on
    # stderr. This is not scoped to the describe/list family -- ANY gcloud
    # call's response can carry a secret this way, so it is checked
    # unconditionally, ahead of the family dispatch, exactly like the
    # identity-mutation checks above it. `CLOUDSDK_CORE_LOG_HTTP` set
    # anywhere in the command is caught separately, at the TOP of decision()
    # (a raw-text substring match across the whole command, not scoped to
    # one segment) -- removed from here in the round 3 fix round (item 5) as
    # genuinely unreachable dead code once that top-level check always fires
    # first; see the comment above `_has_log_http` for the reachability
    # argument. Checked against `gcloud_argv` (B2) -- `raw_argv` would miss a
    # `--log-http` that appears on the gcloud invocation itself when a
    # wrapper/keyword precedes it, since `_has_log_http` only scans ITS OWN
    # argv list positionally, not by skipping a wrapper.
    if _has_log_http(gcloud_argv):
        return (True, "log-http-leaks-response")

    argv = _strip_leading_env_assignments(gcloud_argv)
    rest = argv[1:]
    path = _gcloud_command_path(argv)

    if not path:
        return (False, "")

    # B1 (#5890 round 4 fix round): every DISTINCT path
    # reading `_gcloud_command_path_variants` can produce for this argv --
    # `[path]` itself for every family except `run` (see that function's
    # docstring; identical to `path` when there is no ambiguity). Used only
    # by the describe/list dispatch below, since `run` is the only family
    # with group-level flags and every OTHER check above this point
    # (`config`, `auth`) matches on `path` alone exactly as before -- those
    # verb groups have no group-level flags to be ambiguous about.
    path_variants = _gcloud_command_path_variants(argv)

    # B1 (round 6): the variant walk gave up past `_MAX_PATH_VARIANTS`
    # distinct readings and returned the sentinel instead of enumerating
    # further. Per this module's fail-closed design directive, that is only
    # a BLOCK when this command COULD PLAUSIBLY be a covered describe/list
    # family -- refined (round 6, same-round fix): "starts with `run`" alone
    # is too broad, since `run` also covers non-describe/list verbs like
    # `deploy`/`jobs execute`/`services update` that can NEVER match any
    # covered family under ANY reading (`run deploy --many --unrecognized
    # --flags` legitimately produces many path-reading variants but none of
    # them could ever contain a `services`/`jobs`/`revisions`/
    # `worker-pools`/`configurations` keyword, since readings only differ in
    # which VALUE tokens a flag consumes -- they never invent or hide a
    # literal argv token). The real question is narrower than "starts with
    # run": does this argv contain, as a literal token ANYWHERE, one of the
    # keywords `_RUN_DESCRIBE_LIST_SECOND_ELEMENTS` lists? If not, no
    # reading could ever match a covered family, so this ambiguity is inert
    # and the command falls through to the ordinary dispatch below exactly
    # like any other non-`run`-describe/list command. If the keyword IS
    # present somewhere, this command's true shape genuinely could be an
    # unmasked describe/list under some reading this module gave up trying
    # to enumerate -- denied outright, matching "fail closed only if it's a
    # covered family, never a timeout."
    if tuple(_TOO_MANY_VARIANTS_SENTINEL) in (tuple(v) for v in path_variants):
        if path[:1] == ["run"] and any(tok in _RUN_DESCRIBE_LIST_SECOND_ELEMENTS for tok in rest):
            return (True, "run-path-too-ambiguous")
        path_variants = [path]

    # ---- gcloud config set account | core/account -------------------------
    if path[:2] == ["config", "set"]:
        prop = path[2] if len(path) > 2 else None
        if prop in _ACCOUNT_PROPERTY_NAMES:
            return (True, "config-set-account")
        # ---- gcloud config set log_http | core/log_http (B5) --------------
        # A PERSISTENT, machine-wide route to the same leak --log-http
        # denies per-invocation: this writes the property into the active
        # named configuration, so every subsequent gcloud call on this
        # machine (this session's and every peer's) that doesn't itself
        # override it starts logging the full HTTP response to stderr,
        # including a masked `describe`/`list` this gate otherwise allows.
        if prop in _LOG_HTTP_PROPERTY_NAMES:
            return (True, "config-set-log-http")
        # ---- gcloud config set format | core/format (P3-1) -----------------
        # See `_FORMAT_PROPERTY_NAMES`'s own comment for the exact hazard
        # this defends against: if a future SDK honors this property the way
        # its own `--help` text describes, it silently turns every bare
        # `list` (allowed today on the assumption its own default table
        # output is safe) into a full-dump default for every subsequent
        # gcloud call on this machine.
        if prop in _FORMAT_PROPERTY_NAMES:
            return (True, "config-set-format")
        return (False, "")

    # ---- gcloud config unset account | core/account ------------------------
    # `unset` reaches the identical machine-wide mutation as `set` by deletion
    # instead of assignment: removing the active `account` property forces
    # gcloud to fall back to ADC or prompt on every peer session's next call,
    # re-identifying it exactly like `set account <other>` does (verified
    # against the real installed CLI: `gcloud config unset --help` — "By
    # default, unsets the property in your active configuration only", the
    # SAME active-configuration scope `set` mutates). Both `account` and
    # `core/account` spellings are accepted by `unset` too (gcloud's own
    # `--help` for `set`/`unset`/`get-value` all document accepting either
    # spelling for this property).
    if path[:2] == ["config", "unset"]:
        prop = path[2] if len(path) > 2 else None
        if prop in _ACCOUNT_PROPERTY_NAMES:
            return (True, "config-unset-account")
        return (False, "")

    # ---- gcloud config configurations activate <name> ----------------------
    if path[:3] == ["config", "configurations", "activate"]:
        return (True, "config-configurations-activate")

    # ---- gcloud config configurations create <name> ------------------------
    if path[:3] == ["config", "configurations", "create"]:
        # gcloud activates a freshly created configuration BY DEFAULT (its
        # own --help: "--activate ... Enabled by default, use --no-activate
        # to disable"), which switches the active NAMED CONFIGURATION exactly
        # like `configurations activate` already blocks. `--no-activate` is
        # the same documented flag-presence-allows escape already used for
        # `auth login` below.
        if _has_no_activate(rest):
            return (False, "")
        return (True, "config-configurations-create")

    # ---- gcloud auth activate-service-account ------------------------------
    if path[:2] == ["auth", "activate-service-account"]:
        # No scoping flag exists for this verb (gcloud's own --help: "will
        # also be activated" — unconditional). Denied outright regardless of
        # any --account/--impersonate-service-account token that might also
        # be present, since neither suppresses the activation this verb
        # performs by definition.
        return (True, "auth-activate-service-account")

    # ---- gcloud auth application-default login -----------------------------
    if path[:3] == ["auth", "application-default", "login"]:
        return (True, "auth-application-default-login")

    # ---- gcloud auth application-default revoke -----------------------------
    # Deletes the shared ADC file outright (gcloud's own --help: "deletes the
    # local credential file") -- the same machine-wide-shared file
    # `auth-application-default-login` above is blocked for overwriting, now
    # reached by deletion. No scoping flag exists for this verb.
    if path[:3] == ["auth", "application-default", "revoke"]:
        return (True, "auth-application-default-revoke")

    # ---- gcloud auth revoke [ACCOUNTS...] [--all] ---------------------------
    # With no ACCOUNTS argument, gcloud's own --help: "If no account is
    # specified, this command revokes credentials for the currently active
    # account, effectively logging out of that account" -- the identical
    # machine-wide re-identification `config-set-account` blocks, reached by
    # deletion instead of assignment. WITH an explicit account (or --all),
    # this still removes that account's locally-cached credential outright --
    # a peer session relying on that account (e.g. after a per-command
    # `--account=` override, or because it becomes the active account once
    # this session's own is gone) loses it silently, and there is no scoping
    # flag that revokes without touching the shared on-disk credential store.
    # Denied outright regardless of arguments, mirroring
    # `auth-activate-service-account`'s identical "no scoping flag exists"
    # posture.
    if path[:2] == ["auth", "revoke"]:
        return (True, "auth-revoke")

    # ---- gcloud auth login ---------------------------------------------------
    if path[:2] == ["auth", "login"]:
        # `--update-adc` overwrites the shared ADC file regardless of
        # `--no-activate` (which only suppresses the ACTIVE-ACCOUNT change,
        # not the ADC write) — checked FIRST and independent of
        # `_has_no_activate`, since neither flag authorizes the other's
        # mutation.
        if _has_long_flag(rest, "update-adc"):
            return (True, "auth-login-update-adc")
        if _has_no_activate(rest):
            return (False, "")
        return (True, "auth-login-without-no-activate")

    # ---- gcloud scheduler/run/functions describe -- unredacted secret dump -
    # (#5890): `describe`'s default output is the resource's
    # FULL representation -- headers, env, OIDC/service-account token config
    # -- with no redaction. Denied unless --format is a safe field projection
    # against that resource family's LEAF-field allowlist. `_DESCRIBE_VERB_GROUPS`
    # is ordered longest-path-first within the tuple, so `run jobs executions
    # tasks describe` is tried before the shorter `run jobs executions
    # describe` prefix (B4) -- a shorter prefix match first would misroute
    # the longer command to the wrong family (still correctly denied absent a
    # safe format, but under the wrong family's allowlist).
    #
    # B1: checked against EVERY path reading in `path_variants`, not just the
    # single `path` -- a group-level flag before the verb (`gcloud run
    # services --region us-central1 describe svc`) makes the SINGLE reading
    # miss the match entirely (`us-central1` lands where `describe` should
    # be); the value-consuming reading (`["services", "describe", "svc"]`)
    # is the one that actually matches. `any(...)` -- fail CLOSED on the
    # interpretation: if EITHER reading is a real `describe`/`list` of a
    # covered family, this command is treated as one, matching the block's
    # own documented "unrecognized flag" posture of never trusting the more
    # permissive reading.
    for group, family in _DESCRIBE_VERB_GROUPS:
        n = len(group)
        if any(variant[:n] == list(group) for variant in path_variants):
            if _has_flags_file(rest):
                # B2: a flags file expands in place and may itself set
                # --format to something unsafe with no visible --format
                # token in the command this gate ever sees. Denied
                # unconditionally rather than trusting an absent --format.
                return (True, "describe-flags-file")
            value, present, multiple = _format_value(rest)
            if multiple:
                # B2: gcloud uses the LAST --format value, and a single
                # value can itself concatenate more than one projection --
                # seeing 2+ --format tokens is proof this invocation's real
                # behavior can't be soundly reasoned about from one parsed
                # value. Denied outright regardless of what the last token
                # looks like.
                return (True, "describe-multiple-format")
            if present and _is_safe_format_value(value, family):
                return (False, "")
            return (True, "describe-unmasked-format")

    # ---- gcloud scheduler/run/functions list -- same shape, narrower gate --
    # `list`'s own DEFAULT output is already a summary table (never a full
    # per-resource dump), so no --format at all is fine here -- only an
    # EXPLICIT full-dump format (a bare yaml/json/text kind, or an unsafe
    # projection) is denied. The flags-file and multiple-format checks apply
    # identically to `list`, ahead of the "no --format is fine" allowance,
    # since both are ways gcloud's real output can diverge from what this
    # gate can see in the command it was given. Checked against every
    # `path_variants` reading, same B1 reasoning as `describe` above.
    for group, family in _LIST_VERB_GROUPS:
        n = len(group)
        if any(variant[:n] == list(group) for variant in path_variants):
            if _has_flags_file(rest):
                return (True, "list-flags-file")
            value, present, multiple = _format_value(rest)
            if multiple:
                return (True, "list-multiple-format")
            if not present:
                return (False, "")
            if _is_safe_format_value(value, family):
                return (False, "")
            return (True, "list-unmasked-format")

    return (False, "")


