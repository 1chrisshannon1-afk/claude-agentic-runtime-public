# `false`/`no`/`0` (case-insensitively) as a falsy property value for a
# boolean-shaped property, so these spellings ARE genuinely safe there. The
# FLAG form's own `--no-log-http` (the real, argparse-accepted opt-out) is
# what `_message_for`'s deny text now recommends -- see that function's
# `config-set-log-http`/`log-http-leaks-response` branches.
_FALSE_FLAG_VALUES = frozenset({"false", "no", "0"})


def _has_log_http(argv: list[str]) -> bool:
    """True iff this gcloud invocation's --log-http flag, per gcloud's own
    LAST-FLAG-WINS argparse semantics (the same "last one applies" rule
    `_format_value` already relies on for --format), resolves to TRUE
    (#5890 round 2, B3; P3-2 round 4 fix round narrowed
    this from "any spelling ANYWHERE" to "the LAST spelling's own value").
    `cli.py --help`: "Log all HTTP server requests and responses to stderr"
    -- `transport.py`'s `_LogResponse` prints the full response BODY, which
    reaches tool output identically to stdout regardless of what --format
    was requested; a masked --format only changes what gcloud prints to
    STDOUT, never what --log-http prints to stderr. This check is applied to
    EVERY gcloud verb this module evaluates (see the top of
    `_evaluate_gcloud_argv`), not just the describe/list family, since
    --log-http leaks the response body of ANY gcloud API call.

    P3-2: a bare `--log-http` (no value) or `--log-http=true`/`=yes`/`=1`
    are TRUE. `--log-http=false`/`=no`/`=0` also resolves to FALSE here --
    ROUND 6 CORRECTION (P3-1): this is NOT actually a gcloud-accepted
    mitigation form. `--log-http` is a strict zero-argument boolean flag
    (`actions.StoreBooleanProperty`, `nargs=0` -- see `_FALSE_FLAG_VALUES`'s
    own corrected comment above); passing `=value` to it is a real argparse
    error on the live installed CLI ("ignored explicit argument"), so a
    command using this spelling never actually reaches gcloud successfully
    in the first place. This function still scores `=false`/`=no`/`=0` as
    FALSE rather than TRUE purely as a HARMLESS defensive default (gcloud
    itself errors out before any HTTP call is made, so there is nothing to
    leak either way) -- it is not, and must never be presented as, real
    advice; `_message_for`'s deny text recommends `--no-log-http` (the real,
    argparse-accepted opt-out) instead. `--no-log-http` (the auto-generated
    paired flag every `StoreBooleanProperty` registration gets) is FALSE.
    Only the LAST occurrence in argv counts, so `--log-http --no-log-http`
    (mitigation applied after an earlier accidental flag) correctly resolves
    to FALSE, not TRUE."""
    resolved: bool | None = None
    for a in argv:
        if a == "--log-http":
            resolved = True
        elif a == "--no-log-http":
            resolved = False
        elif a.startswith("--log-http="):
            value = a[len("--log-http=") :]
            resolved = value.strip().lower() not in _FALSE_FLAG_VALUES
    return bool(resolved)


def _gcloud_token(tok: str) -> bool:
    """True iff `tok` is, by ITSELF, a gcloud program token: the exact
    literal `gcloud`, or a path whose final component is `gcloud`
    (`/usr/bin/gcloud`, `./gcloud`, `/opt/homebrew/.../gcloud`)."""
    return tok == "gcloud" or tok.rsplit("/", 1)[-1] == "gcloud"


def _find_gcloud_argv(argv: list[str]) -> list[str] | None:
    """THE single shared "is this really a gcloud invocation, and if so what
    is its own argv" helper (B2, #5890 round 4 fix round).

    Scans EVERY token in `argv`, in order, for the first one that is itself
    a gcloud program token (`_gcloud_token`). Returns `argv` sliced starting
    at that token (so `argv[found:]` -- `gcloud` and everything after it,
    exactly the shape every other function in this module already expects
    as "a gcloud invocation's own argv"), or `None` if no token in `argv` is
    ever a gcloud program token.

    This REPLACES the pre-B2 approach of walking past a FIXED, enumerated
    set of wrapper tokens (`env`, `sudo`, `command`, `exec` — the old
    `_PROGRAM_WRAPPER_TOKENS`) one at a time from the front. That approach
    required every wrapper, shell keyword, or prefix tool that can precede a
    real command to be indvidually listed and kept in sync -- and B2 found it
    never was: `time`, `timeout N`, `nohup`, `xargs [...]`, the shell
    keywords `do`/`then`/`else`/`{`/`!` (each of which `_split_segments`
    legitimately leaves as its own segment's first token or leading text,
    e.g. `do gcloud scheduler jobs describe $j`), and any FUTURE wrapper not
    yet invented all walked straight past the old check, silently returning
    "not gcloud" for a segment that unquestionably invokes gcloud.

    Scanning every token instead of walking a fixed prefix list needs no
    wrapper enumeration at all: `gcloud` (or a path ending in it) is simply
    the first token, wherever it is, that IS the program. The accepted
    tradeoff (documented, not silently eaten): a token that merely CONTAINS
    "gcloud" as text without being the program -- `echo gcloud config set
    account x` (an argument to `echo`, never executed as a program) -- now
    also matches, since this function has no notion of "argument position"
    once it stops trying to track a specific wrapper's own arity. This is a
    rare FALSE POSITIVE (a harmless echo/printf/comment-shaped command
    treated as if it invoked gcloud), never a false negative, and the
    correct direction for a security gate to err in -- the same posture
    `_mentions_gcloud`'s own docstring already accepts for its whole-word
    fallback on unparseable text.

    Never raises: any internal error returns None (the caller then treats
    the argv as not a gcloud invocation, matching this module's fail-open
    default for internal bugs -- OUTER callers like `_mentions_gcloud` still
    have their own fail-closed handling for the specific unparseable-text
    case, unaffected by this function's own contract)."""
    try:
        for i, tok in enumerate(argv):
            if _gcloud_token(tok):
                return argv[i:]
        return None
    except Exception:
        return None


# Hard cap on how many gcloud-token-starting slices `_find_all_gcloud_argv_slices`
# will ever return for one segment's argv (ROUND 6, P2-2) -- bounded for the
# same reason every other loop in this module is bounded: a segment cannot
# have more gcloud-shaped tokens than it has tokens at all, so this is
# already implicitly bounded by argv length, but an explicit small ceiling
# keeps the cost of evaluating every slice trivially small regardless.
_MAX_GCLOUD_SLICES = 16


def _find_all_gcloud_argv_slices(argv: list[str]) -> tuple[list[list[str]], bool]:
    """Every DISTINCT `argv` slice starting at a token that is itself a
    gcloud program token (ROUND 6, P2-2) -- not merely the FIRST one
    `_find_gcloud_argv` returns -- plus whether the search was TRUNCATED by
    `_MAX_GCLOUD_SLICES` before it could finish scanning `argv` (ROUND 7,
    P3-a).

    ROUND 6 CORRECTION (P2-2): `_find_gcloud_argv`'s own docstring already
    documents accepting a rare false positive when an EARLIER argument
    merely contains the word "gcloud" without being the program (`echo
    gcloud ...`) -- but it never anticipated an earlier argument that itself
    ENDS in `/gcloud` as a PATH, not a program invocation, with a REAL
    gcloud invocation later in the same argv: `docker run -v
    ~/.config/gcloud:/root/.config/gcloud IMAGE gcloud run services describe
    s` -- `_gcloud_token` matches `~/.config/gcloud:/root/.config/gcloud` (a
    single shlex token whose suffix, after the LAST `/`, is `gcloud`) before
    it ever reaches the real `gcloud run services describe s` later in the
    same argv, and `_find_gcloud_argv` returns only the FIRST match,
    silently missing the real invocation entirely. `sudo
    --preserve-env=/x/gcloud gcloud config set account x` is the identical
    shape: `--preserve-env=/x/gcloud` ends in `/gcloud` as a flag VALUE, not
    a program.

    Rather than trying to distinguish "ends in /gcloud as a real program
    token" from "ends in /gcloud as an unrelated path/flag-value" (a
    fundamentally unreliable distinction from argv alone -- a Docker
    `-v SRC:DST` argument and a real program path share the identical
    textual shape), this returns EVERY slice starting at a gcloud-shaped
    token, capped at `_MAX_GCLOUD_SLICES`, so the caller
    (`_evaluate_gcloud_argv`'s caller) can evaluate each one and block if ANY
    is a real, dangerous gcloud invocation -- fail CLOSED on the
    interpretation, the same posture this module already takes for B1's
    path-reading ambiguity: never trust that the FIRST match is the only
    real one.

    ROUND 7 CORRECTION (P3-a): the round-6 version stopped collecting once
    it hit `_MAX_GCLOUD_SLICES` and returned exactly those slices with no
    signal that more existed -- so the caller evaluated only the FIRST 16
    gcloud-shaped tokens and silently treated argv as safe if none of THOSE
    16 were dangerous, even when a real, dangerous invocation sat at
    position 17+ (repro: 20 `-v /hN/gcloud:/cN/gcloud` Docker mounts before
    the real `gcloud run services describe s`/`gcloud config set account x`
    -- both silently ALLOWED). This directly contradicted this module's own
    "bounded rules fail CLOSED, never silently allow past the bound"
    directive: a bound that stops LOOKING must never be read by its caller
    as "nothing more to find." Fixed by returning a second value,
    `truncated`, True iff the scan stopped because it hit the cap with more
    of `argv` left unscanned -- the caller now denies outright
    (`untokenizable-segment-with-gcloud`) whenever `truncated` is True,
    never evaluating only a partial slice list as if it were complete.

    Never raises: any internal error returns `([], True)` -- fail CLOSED on
    an internal bug too (ROUND 7: widened from the round-6 fail-OPEN-on-bug
    default, `[]`/no signal, since this function's job is now explicitly
    "prove there is nothing dangerous left to find," and a bug here cannot
    prove that)."""
    try:
        out: list[list[str]] = []
        n = len(argv)
        for i, tok in enumerate(argv):
            if len(out) >= _MAX_GCLOUD_SLICES:
                # More of argv may remain unscanned -- report truncation
                # unless this was genuinely the last possible position a
                # slice could have started (nothing left to miss).
                return (out, i < n)
            if _gcloud_token(tok):
                out.append(argv[i:])
        return (out, False)
    except Exception:
        return ([], True)


def _is_gcloud(argv: list[str]) -> bool:
    """True iff `argv` (a single command segment's own argv, exactly as
    `shlex.split` produced it -- e.g. what `_gcloud_segments` hands to
    `_evaluate_gcloud_argv`) invokes `gcloud` anywhere in its tokens, per
    `_find_gcloud_argv` (B2, round 4 fix round). Historically this only
    stripped a LEADING env-assignment prefix and checked `argv[0]` -- see
    `_find_gcloud_argv`'s own docstring for why that missed every wrapper/
    keyword shape B2 found."""
    return _find_gcloud_argv(argv) is not None


def _gcloud_command_path(argv: list[str]) -> list[str]:
    """Given a gcloud invocation's argv (env-assignment prefix already
    stripped, `argv[0]` is the `gcloud` program token), return the
    subcommand "path" -- every non-flag token, positionally, skipping any
    flag token and (for a global flag spelled with a separate-token value
    rather than `--flag=value`) its value token too -- with a leading
    `alpha`/`beta` release-track element also stripped.

    Factored out of `_evaluate_gcloud_argv` so `_family_for_command` (used
    only to build a per-family deny-message hint, #5890
    round 2 B6) can compute the IDENTICAL path `_evaluate_gcloud_argv` used
    to pick a verb group, without duplicating this flag-walk logic a second
    time -- the B1 regression this walk itself fixed (a flag before the path
    truncating it to empty) is exactly the class of bug duplicated logic
    invites.

    gcloud accepts global flags (--account, --impersonate-service-account,
    --configuration, --quiet, --verbosity, ...) BEFORE, interspersed with, or
    after the subcommand path (verified by execution: `gcloud --quiet config
    set --help` and `gcloud --verbosity=debug config set --help` both parse
    and exit 0) — so this scans positionally rather than assuming a fixed
    prefix length, and rather than stopping at the FIRST flag token (B1: a
    flag before the path, e.g. `--quiet` or `--verbosity=debug`, must never
    truncate the path to empty and thereby allow the whole command through).
    `--account=x gcloud config set account y` and `gcloud --account x config
    set account y` are exactly as real a bypass attempt as any other
    ordering, so this walks the ENTIRE `rest`, never `break`ing on the first
    flag, and collects every non-flag, non-flag-value token into `path`.
    """
    rest = argv[1:]
    path: list[str] = []
    i = 0
    while i < len(rest):
        tok = rest[i]
        if not tok.startswith("-"):
            path.append(tok)
            i += 1
            continue
        # A flag token. Does it carry its value inline (`--flag=value`) or
        # as a bare boolean (`--quiet`, `-q`, ...)? Either way, no extra
        # token to skip.
        if "=" in tok or tok in _GLOBAL_BOOLEAN_SHORT_FLAGS:
            i += 1
            continue
        name = tok[2:] if tok.startswith("--") else tok[1:]
        if tok.startswith("--") and name in _GLOBAL_BOOLEAN_FLAGS:
            i += 1
            continue
        if tok.startswith("--") and name in _GLOBAL_VALUE_FLAGS:
            # Space-separated form (`--account foo@bar.com`): skip the flag
            # AND its value token, so the value never gets mistaken for
            # (or masks) the next subcommand-path token.
            i += 2
            continue
        # An unrecognized flag (a subcommand-local flag, e.g. `--key-file=`
        # already handled above via the `"=" in tok` branch, or a bare
        # subcommand-local boolean like `--async`). Treat conservatively as
        # a no-value flag — skip just the one token — so an unknown flag can
        # never silently swallow the next real path token and, symmetrically,
        # can never be misread as extending the path itself.
        i += 1

    if not path:
        return []

    # `alpha`/`beta` release-track prefixes expose the IDENTICAL command
    # surface one path element later (verified against the real installed
    # CLI: `gcloud alpha config set --help` / `gcloud beta auth login --help`
    # both resolve to the same command as their non-prefixed form) — strip a
    # single leading track element so every verb match below applies
    # regardless of track. Only a LEADING element counts: `gcloud config
    # alpha` (were such a subcommand to exist) must not have its `alpha`
    # stripped from the middle of the path.
    if path[:1] in (["alpha"], ["beta"]):
        path = path[1:]

    return path


