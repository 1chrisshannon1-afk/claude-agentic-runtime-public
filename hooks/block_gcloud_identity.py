# gcloud's field-PROJECTION format kinds — a format value shaped like
# `KIND(field,field,...)` names an explicit, closed field list rather than
# dumping the resource's entire representation. Verified against the real
# installed CLI (`gcloud topic formats`): yaml/json/table/value/csv all
# accept this projection syntax. Anchored end-to-end (`$`), but this does NOT
# reject a concatenated multi-projection value like `table(name) json()` at
# the regex stage -- ROUND 2 CORRECTION (D1): an earlier version of this
# comment (and `_is_safe_format_value`'s own docstring below) claimed the
# anchoring makes that shape "fail the match entirely." It doesn't: `.*`
# inside the parens is greedy, so `table(name) json()` matches with
# `fields="name) json("` (spanning through to the LAST closing paren, not
# the first). What actually denies this shape is `_is_safe_format_value`'s
# per-field allowlist check below -- splitting `"name) json("` on `,` yields
