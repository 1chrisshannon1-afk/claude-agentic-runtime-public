# Reused from block_branch_ops.py / block_head_overwrite.py — the same
# operator-only escape hatch, not a new var, so an operator does not need to
# remember a third name for the identical class of override.
ESCAPE_VAR = "CSA_ALLOW_GIT_STATE_OPS"

# `account` and `core/account` name the SAME property (`account` lives in the
# `core` section; both spellings are accepted by `gcloud config set/unset/
# get-value`). Either spelling mutating the ambient identity is blocked.
_ACCOUNT_PROPERTY_NAMES = frozenset({"account", "core/account"})

# `log_http` and `core/log_http` name the SAME property (`log_http` lives in
# the `core` section, exactly like `account` above) -- ExampleApp
# #5890 round 2, B5. `gcloud config set core/log_http true` is PERSISTENT and
# machine-wide (written to the active named configuration, read by every
# subsequent gcloud invocation on this machine that doesn't override it),
# unlike the per-invocation `--log-http` flag this module already denies on
# every verb. Once set, every masked `describe`/`list` this gate allows in
# any live session starts leaking its full, unmasked HTTP response on stderr
# -- the same "one shared mutable property, many concurrent readers" hazard
# `config-set-account` already exists to block, reached via a different
# property name.
_LOG_HTTP_PROPERTY_NAMES = frozenset({"log_http", "core/log_http"})

# `format` and `core/format` name the SAME property (P3-1, round 4 fix
# round) -- `gcloud --help`'s own "core/format" property description says it
# "Overrides the default format used when the --format flag is not present."
# On the installed SDK (574.0.0), setting `CLOUDSDK_CORE_FORMAT=json` on a
# bare `gcloud scheduler jobs list` had NO observed effect (the response
# still rendered as a table -- the first non-whitespace character was `N`,
# the table header, not `[`), so this hazard is UNVERIFIED as exploitable
# TODAY -- but the property's own documented purpose is exactly "change what
# every bare command without --format prints," and IF a future SDK version
# ever honors it, every bare `list` this module allows with no --format
# (its own default table output is presumed safe) would silently become a
# full JSON/yaml dump of every listed resource, defeating this whole
# module's `describe`/`list` masking requirement at the property level
# rather than per-invocation. Denied defensively now, before it is ever
# observed live, rather than waiting for a live exploit to justify it.
_FORMAT_PROPERTY_NAMES = frozenset({"format", "core/format"})

# gcloud's GLOBAL flags that take a value as a SEPARATE token when spelled
# without `=` (`--account foo@bar.com`, not just `--account=foo@bar.com`) —
# verified against `gcloud --help`'s own "GLOBAL FLAGS" section (executed
# 2026-09-13: every one of these accepts both the `--flag=value` and
# `--flag value` spellings; `gcloud --account foo@bar.com config list --help`
# and `gcloud --verbosity debug config set --help` both parse and exit 0).
# This list is deliberately the GLOBAL flag set only (gcloud accepts these
# before, interspersed with, or after the subcommand path) — a value-taking
# flag local to a specific subcommand (e.g. `config set`'s own
# `--installation`) never appears before the subcommand path is fully
# consumed, so it cannot mask the path the way a global flag can, and is out
# of scope for this positional walk.
#
# CORRECTION (B1, round 4 fix round): the claim above -- that only a GLOBAL
# flag can appear before the subcommand path is fully consumed -- is FALSE
# for a GROUP-LEVEL flag (one declared by a subcommand GROUP's own `Args()`,
# not gcloud-wide). `gcloud run services --region us-central1 describe svc`
# is real, accepted gcloud syntax: `run services`/`run jobs`/`run revisions`
# each declare `--region`/`--platform`/`--cluster`/`--cluster-location`/
# `--context`/`--kubeconfig` at the GROUP level (see `_RUN_GROUP_VALUE_FLAGS`
# below), so those flags legitimately precede the verb too, exactly like a
# global flag would, and this single-reading walk alone would swallow only
# the flag token and misread its value as the next path element -- the B1
# bypass. `_gcloud_command_path_variants()` (below) is the fix: when the
# eventual first path element could be `run` (the only family with
# group-level flags -- confirmed `scheduler`/`functions` have none), it
# additionally computes the ALTERNATE reading for every unrecognized
# space-separated flag and returns every distinct path so the caller can
# check both. This function (`_gcloud_command_path`) keeps its single-reading
# behavior unchanged -- it is still correct and sufficient for every
# non-`run` family and for every identity-mutation check above, since none of
# those verb groups (`config`, `auth`) has a group-level flag either.
_GLOBAL_VALUE_FLAGS = frozenset(
    {
        "account",
        "billing-project",
        "configuration",
        "flags-file",
        "flatten",
        "format",
        "project",
        "verbosity",
        "access-token-file",
        "impersonate-service-account",
        "trace-token",
        # Added #5890 fix round (in-change item): missing
        # from this list, a value-taking global flag before the subcommand
        # path masks the path exactly like the B1 `--quiet`/`--verbosity`
        # regression class already fixed -- `gcloud --http-timeout 30
        # scheduler jobs describe j` AND `gcloud --http-timeout 30 config set
        # account x@y.com` both passed pre-fix (the second is a bypass of the
        # PRE-EXISTING identity gate too, not just the #5890 describe gate).
        # Verified against `gcloud --help`'s own "GLOBAL FLAGS" section.
        "http-timeout",
        "authority-selector",
        "authorization-token-file",
        "credential-file-override",
        "universe-domain",
    }
)

# gcloud's GLOBAL flags that take NO value (boolean/presence-only) — verified
# against `gcloud --help`'s "GLOBAL FLAGS" section. `-q` is `--quiet`'s short
# form; `-v` is `--version`'s.
_GLOBAL_BOOLEAN_FLAGS = frozenset(
    {"help", "quiet", "version", "log-http", "user-output-enabled"}
)
_GLOBAL_BOOLEAN_SHORT_FLAGS = frozenset({"-q", "-v"})

# GROUP-LEVEL value-taking flags for the `run` command surface (B1,
# #5890 round 4 fix round): unlike `_GLOBAL_VALUE_FLAGS`
# above (gcloud-WIDE flags valid before/after/interspersed with ANY
# subcommand), these are declared by the SUBCOMMAND GROUP itself and are only
# valid on that group's own command tree -- but critically, gcloud still
# accepts them BEFORE the verb (`gcloud run services --region us-central1
# describe svc`), exactly like a global flag would, because argparse parses
# them at the group's own parser level. Verified against the real installed
# CLI (SDK 574.0.0) and the SDK's own source:
#   * `run services` / `run revisions`: `surface/run/services/__init__.py` /
#     `surface/run/revisions/__init__.py` both call
