# Fallback hint used only when `family` is somehow not a recognized key (this
# should never happen in practice -- every call site below passes a family
# drawn from `_DESCRIBE_VERB_GROUPS`/`_LIST_VERB_GROUPS`, which are the only
# source of a `family` value reaching `_message_for`). Kept as the original
# scheduler-job example rather than raising, matching this module's
# fail-toward-a-working-message posture.
_SAFE_FORMAT_HINT_FALLBACK = "table(name,schedule,state)"


def _safe_format_hint(family: str | None = None) -> str:
    """The operator/agent-facing example of a safe masked `--format` for
    `family` (#5890 round 2, B6). Returns a projection
    built from THAT family's own `_SAFE_LEAF_FIELDS` entries, since a single
    shared example (the pre-round-2 behavior) passes `decision()` for only
    one family and denies an agent that follows it for any other. `family`
    is optional and defaults to the fallback hint so an unexpected/unknown
    family degrades to a still-working (for scheduler-job) example rather
    than raising."""
    if family is None:
        return "--format='" + _SAFE_FORMAT_HINT_FALLBACK + "'"
    return "--format='" + _SAFE_FORMAT_HINTS.get(family, _SAFE_FORMAT_HINT_FALLBACK) + "'"


