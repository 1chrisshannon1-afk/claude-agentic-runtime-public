#!/usr/bin/env python3
"""block_gcloud_identity — PreToolUse:Bash hook.

Blocks a Bash command that would MUTATE the machine's shared, ambient gcloud
identity (the active account in ``gcloud config``, or the on-disk Application
Default Credentials file). #5310: `gcloud config`/`gcloud auth`'s "active
account" and `~/.config/gcloud/application_default_credentials.json` are
MACHINE-WIDE state — there is exactly one of each on this machine, shared by
every concurrently-running agent session, exactly like the shared git working
tree `block_branch_ops.py`/`file_claims.py` already protect. An agent that
runs `gcloud config set account other@x.com` (or activates a service account,
or overwrites ADC) silently re-identifies EVERY other live session's next
`gcloud`/ADC-consuming call on this machine, with no per-session isolation —
the gcloud equivalent of `git checkout`ing a shared branch out from under a
peer session, which is exactly why `checkout`/`switch` are already
STATE_VERBS in `block_branch_ops.py`.

BLOCKS (unconditionally reserved for the operator — none of these carries a
per-command scoping form that leaves the AMBIENT identity untouched, which is
precisely why they're blocked outright rather than merely discouraged):
  * `gcloud config set account <val>`         (also `core/account` spelling —
    `account` IS the `core` section's property; both name the same setting)
  * `gcloud config configurations activate <name>`   (switches the active
    NAMED CONFIGURATION, whose properties include `account`)
  * `gcloud auth activate-service-account ...`        (re-identifies as a
    service account AND sets it active — `gcloud auth activate-service-account
    --help`: "Credentials will also be activated (similar to running gcloud
    config set account [ACCOUNT_NAME])" — there is no flag that activates
    WITHOUT also becoming the ambient active account, unlike `auth login`'s
    own `--no-activate`, so this verb is denied outright rather than gated on
    a flag that doesn't exist)
  * `gcloud auth application-default login ...`       (overwrites the shared
    ADC file at the well-known location — no scoping flag suppresses this)
  * `gcloud auth login ...` WITHOUT `--no-activate`    (a bare `gcloud auth
    login` sets the active account exactly like `config set account` would;
    `--no-activate` is gcloud's own documented way to authorize without
    becoming the ambient identity, so ITS presence is what allows the
    command through, not a documented alternative form)
  * a shell redirect/copy/move/link/sync that WRITES
    `~/.config/gcloud/application_default_credentials.json` directly (`>`,
    `>>`, `cp`/`mv`/`ln`/`install`/`rsync ... application_default_credentials.json`,
    `dd of=.../application_default_credentials.json`, `tee
    .../application_default_credentials.json`) — including the
    directory-destination form (`cp /tmp/key.json ~/.config/gcloud/`, which
    preserves the source file's own `application_default_credentials.json`
    basename at the destination) — the same class of filesystem-level bypass
    `block_head_overwrite.py` already treats as equally real and equally
    dangerous as the git-native verb it parallels. Known remaining gap (not
    covered — see the module's own comment where the writer program set is
    defined): an interpreter one-liner that opens and writes the path
    programmatically (`python3 -c "open(...).write(...)"`) has no shell-level
    argv shape to detect against; this is a documented limitation, not a
    silent one.
  * every blocked verb above ALSO under the `alpha`/`beta` release-track
    prefix (`gcloud alpha config set account ...`, `gcloud beta auth login`,
    ...) — gcloud exposes the identical command surface under those tracks
    (verified against the real installed CLI: `gcloud alpha config set
    --help` and `gcloud beta auth login --help` both resolve to the exact
    same command). A leading `alpha`/`beta` path element is stripped before
    every verb match below, so the track prefix can never mask the verb it
    precedes.
  * `gcloud auth login ... --update-adc` REGARDLESS of `--no-activate` —
    `--update-adc` writes the shared ADC file (gcloud's own `--help`: "Write
    the obtained credentials to the well-known location for Application
    Default Credentials... Any credentials previously generated by gcloud
    auth application-default login will be overwritten"), the exact
    machine-wide mutation `auth-application-default-login` above already
    blocks outright, reachable via a second verb. `--no-activate` only
    suppresses the ACTIVE-ACCOUNT change; it does nothing about the ADC
    write, so it does not authorize this flag combination.
  * `gcloud config configurations create <name>` WITHOUT `--no-activate` —
    gcloud activates a newly created configuration by default (`gcloud config
    configurations create --help`: "--activate — Enabled by default, use
    --no-activate to disable"), which switches the active NAMED
    CONFIGURATION exactly like `config configurations activate` already
    blocks. `--no-activate` here is the same documented flag-presence-allows
    escape this module already implements for `auth login`.
  * `gcloud config unset account | core/account`      (deletion reaches the
    identical machine-wide mutation `config set account` blocks — gcloud's
    own `--help`: "By default, unsets the property in your active
    configuration only", the same active-configuration scope `set` mutates —
    a removed `account` property re-identifies every peer session's next
    call exactly as an assignment would)
  * `gcloud auth revoke [ACCOUNTS...] [--all]`        (with no account
    argument, gcloud's own `--help`: "revokes credentials for the currently
    active account, effectively logging out of that account" — the same
    re-identification `config set account` performs, reached by deleting the
    credential instead of reassigning it; WITH an explicit account or `--all`,
    it still removes that account's locally-cached credential from the
    shared credential store outright, with no scoping flag that limits the
    removal to the caller's own session — denied unconditionally, mirroring
    `auth-activate-service-account`'s identical "no scoping flag exists"
    posture)
  * `gcloud auth application-default revoke`          (deletes the shared ADC
    file outright — gcloud's own `--help`: "deletes the local credential
    file" — the same well-known, machine-wide-shared path
    `auth-application-default-login` is blocked for overwriting, now reached
    by deletion; no scoping flag exists)
  * `gcloud [alpha|beta] scheduler jobs describe <job>` / `run services
    describe <svc>` / `run jobs describe <job>` / `run revisions describe
    <rev>` / `run jobs executions describe <exec>` / `run jobs executions
    tasks describe <task>` / `functions describe <fn>` WITHOUT a safe
    `--format` field projection (#5890): these `describe`
    commands print the resource's FULL representation to stdout by default,
    and stdout is tool output the model reads. A Scheduler job's
    `httpTarget.headers` can carry a literal secret value (e.g.
    `X-Scheduler-Key`), a Cloud Run revision's env can carry plaintext
    secrets, and an OIDC/service-account token config is itself sensitive —
    none of that is redacted by gcloud's own default output. See
    `~/.claude/knowledge/gcloud_identity_is_machine_wide.md`'s
    scheduler/IaC section for the masked `--format` convention this blocks
    toward. "Safe" means a field-PROJECTION format (`yaml(...)`, `json(...)`,
    `table(...)`, `value(...)`, `csv(...)`, each with a non-empty field
    list) whose EVERY field is an exact (case-insensitive) match against a
    per-resource-family ALLOWLIST of known-safe LEAF fields
    (`_SAFE_LEAF_FIELDS`) — not a "doesn't look unsafe" blocklist: round 2 of
    #5890 found a per-field substring blocklist cannot see that a PARENT key
    (e.g. `httpTarget`, `spec`) contains unsafe children even though the
    parent's own name looks benign, since gcloud prints that key's entire
    subtree. A bare `--format=yaml`/`json`/`text` (no field list — dumps the
    whole resource), no `--format` at all (gcloud's own default `describe`
    output is a full dump), a `.`/`*` wildcard field, an empty field, or a
    projection naming any field outside that family's allowlist (parent key
    or otherwise), are all denied. Also denied, on EVERY covered `describe`/
    `list` verb: `--flags-file` (a flags file expands in place and may set
    `--format` to something unsafe with no `--format` token visible in the
    command this gate ever sees), and 2+ `--format` tokens (gcloud applies
    the LAST one, and a single value can itself concatenate more than one
    projection — `--format='table(name) json()'` — so this gate denies
    outright rather than trusting a parse of just the first token).
  * `gcloud [alpha|beta] scheduler jobs list` / `run services list` / `run
    jobs list` / `run revisions list` / `run jobs executions list` / `run
    jobs executions tasks list` / `functions list` are allowed with NO
    `--format` (their default table output is already a summary, not a
    full-resource dump) or a safe leaf-field-allowlisted projection, and
    denied with an explicit full-dump format (`--format=yaml`/`json`/`text`
    with no field list) OR a projection naming a field outside the
    allowlist — the same allowlist check `describe` applies, not merely the
    bare-full-dump-format check alone.
  * `gcloud <any subcommand>` carrying `--log-http` resolving TRUE per
    gcloud's own LAST-FLAG-WINS semantics (any spelling: bare `--log-http`,
    `--log-http=true`/`=yes`/`=1` — `--log-http=false`/`=no`/`=0`/
    `--no-log-http` do NOT deny, P3-2 round 4 fix round) or
    `CLOUDSDK_CORE_LOG_HTTP` resolving ACTIVE (an `unset`/`env -u` mitigation
    form does NOT deny, same P3-2 fix), on a command that ACTUALLY INVOKES
    gcloud SOMEWHERE (#5890 round 2, then round 2 fix
    round B5 widened this from a leading-env-prefix-on-the-SAME-segment
    check to a raw-text substring match across the WHOLE command, since
    `export CLOUDSDK_CORE_LOG_HTTP=1; gcloud ...` / `env
    CLOUDSDK_CORE_LOG_HTTP=1 gcloud ...` / `set -a; CLOUDSDK_CORE_LOG_HTTP=1;
    set +a; gcloud ...` all set the SAME property from a DIFFERENT shell
    segment than the gcloud call, invisible to a per-segment leading-prefix
    check; round 4 fix round B2 widened "actually invokes gcloud" further,
    from a top-level-segments-only program-token scan to ALSO recurse into
    any `bash -c`/`eval` argument, heredoc body fed to a shell interpreter,
    or `$(...)`/backtick command-substitution span, via
    `_mentions_gcloud_anywhere` — see that function's own docstring):
    `--log-http` prints the FULL HTTP request/response body to stderr
    regardless of what `--format` was requested — a masked `--format` only
    changes what gcloud writes to STDOUT, never what `--log-http` writes to
    stderr. Applied to EVERY gcloud verb this module evaluates, not only the
    scheduler/run/functions describe/list family, since any gcloud API
    call's response can carry a secret this way.
  * `gcloud config set log_http|core/log_http <val>` (round 2 fix round,
    B5): the PERSISTENT, machine-wide route to the identical leak
    `--log-http` denies per-invocation — this writes the property into the
    active named configuration, so every subsequent gcloud call on this
    machine (this session's and every peer's) that doesn't itself override
    it starts logging the full HTTP response to stderr, including a masked
    `describe`/`list` this gate otherwise allows. Known remaining gap (not
    covered, same posture as the shell-profile-export gap below): a direct
    write of `log_http`/`core/log_http` into
    `~/.config/gcloud/configurations/config_<name>` bypassing the `gcloud`
    CLI entirely has no argv shape for this module to inspect, mirroring the
    ADC-file-write detection's own documented interpreter-one-liner gap
    above.

  DENY REASON STRINGS this module returns for the scheduler/run/functions
  describe/list + `--log-http`/`log_http` hazard class above (round 2 fix
  round, D1 — named here so a reader of `~/.claude/.enforcement/log.jsonl`
  can find their meaning without cross-referencing `_message_for`; round 6,
  B4: this list previously omitted `config-set-format`/`format-env-override`,
  added round 4, and `run-path-too-ambiguous`, added round 6 -- both are
  included now):
  `describe-unmasked-format`, `list-unmasked-format`,
  `describe-multiple-format`, `list-multiple-format`, `describe-flags-file`,
  `list-flags-file`, `log-http-leaks-response`, `config-set-log-http`,
  `config-set-format`, `format-env-override`, `run-path-too-ambiguous`.

ALLOWS (the per-command / per-process scoping forms that leave the ambient
identity untouched, exactly what #5310 asks every session to use
instead):
  * `gcloud --account=<val> <cmd>` / `gcloud <cmd> --account=<val>` (any
    position; a PER-INVOCATION override, never touches the active config)
  * `CLOUDSDK_CORE_ACCOUNT=<val> gcloud <cmd>` (a per-process env override,
    same reasoning)
  * `--impersonate-service-account=<val>` (also per-invocation; the
    task's own remediation text for the activate-service-account block)
  * `gcloud auth list`                     (read-only enumeration)
  * `gcloud config get-value account`      (read-only query)
  * `gcloud scheduler jobs describe <job> --format='table(name,schedule,state)'`
    (or `yaml(...)`/`json(...)`/`value(...)`/`csv(...)`, ROUND 2 (D1): a
    non-empty field list whose EVERY field is an exact, case-insensitive
    match against that resource family's own `_SAFE_LEAF_FIELDS` allowlist
    -- not "names no unsafe field", a blocklist framing this module
    deliberately does NOT use post-round-2, since a field can be absent from
    an allowlist without looking unsafe by name; see `_SAFE_FORMAT_HINTS`
    for the working example projection per family) — the masked-projection
    form the scheduler/run/functions `describe` block above asks every
    session to use instead of a full-resource dump.
  * every other read-only/non-identity-mutating gcloud subcommand, and every
    non-gcloud command.

KNOWN SCOPE GAP (deliberate, documented, not silent — see
`~/.claude/knowledge/gcloud_identity_is_machine_wide.md`'s own "Known scope
gap" section for the full writeup): #5310's checklist additionally names
a shell-profile credential export (e.g. appending
`export GOOGLE_APPLICATION_CREDENTIALS=...` to `~/.zshrc`) as an incident
mutation. `GOOGLE_APPLICATION_CREDENTIALS` takes precedence over the ADC file
this gate protects, and a profile export persists across every new shell
exactly like the ADC file does — but this gate does NOT detect that shape.
Blocking an arbitrary write to an arbitrary shell-profile file is a much
broader detection surface than one well-known JSON path and needs its own
scoped design, not a bolt-on here.

KNOWN DELIBERATE-ATTACKER GAPS (round 3 fix round, item 4 — documented here,
not silent, same posture as every gap above; each is a shape this module
cannot see from a Bash command's argv/text alone, deliberately excluded
rather than chased with an ever-widening blocklist that would still miss the
next variant):
  * the ADC-file-write direct-write gap already named above (an interpreter
    one-liner that opens and writes the ADC path programmatically has no
    shell-level argv shape to detect against);
  * the `log_http`/`core/log_http` direct-config-write gap already named
    above (writing the property straight into
    `~/.config/gcloud/configurations/config_<name>` bypasses the `gcloud`
    CLI entirely, mirroring the ADC gap immediately above it);
  * a RUNTIME-BUILT env var NAME that only resolves to
    `CLOUDSDK_CORE_LOG_HTTP` at shell-execution time
    (`CLOUDSDK_CORE_LOG_$(echo HTTP)=1 gcloud ...`, or the equivalent via
    command substitution / indirect expansion / `eval`) — the
    CLOUDSDK_CORE_LOG_HTTP raw-text substring check in `decision()` matches
    the LITERAL string only; a command-substitution-assembled variable name
    never appears as that literal substring anywhere in the command text,
    so this gate cannot see it forming the same property at all;
  * `source`-ing (or `.`-ing) a file that itself sets
    `CLOUDSDK_CORE_LOG_HTTP`, `CLOUDSDK_CORE_ACCOUNT`, or any other
    identity/log-http-relevant env var (`source ./env.sh; gcloud ...`) — the
    assignment lives in a file this module never reads (it does no I/O by
    contract, mirroring every sibling gate's pure-decision-function
    contract), so the sourced file's content is invisible to both the
    raw-text CLOUDSDK_CORE_LOG_HTTP check and the per-segment env-prefix
    walk; only an assignment appearing LITERALLY in the command string
    itself is ever detected;
  * `CLOUDSDK_CONFIG` pointed at an alternate configuration directory
    (`CLOUDSDK_CONFIG=/tmp/altconfig gcloud ...`, or exported in a prior
    segment) — every `gcloud config set`/`unset` check in this module
    reasons about property NAMES (`account`, `log_http`, ...), never about
    WHICH on-disk configuration directory gcloud actually reads/writes; a
    session that points `CLOUDSDK_CONFIG` at a directory outside the
    well-known shared location sidesteps this module's entire "machine-wide,
    shared by every session" threat model for whatever properties live
    there, without tripping any check here, since nothing in this module
    inspects `CLOUDSDK_CONFIG` at all.
None of these are chased here: each requires either executing/parsing
arbitrary shell (defeating the "no I/O, no subprocess, pure decision
function" contract every sibling gate shares) or a fundamentally different
detection strategy (e.g. sandboxing gcloud's actual file I/O rather than
guessing at it from argv text). Documented so a future reviewer or repo
audit does not mistake "this class of check exists" for "this class of
check is complete."

DETECTION STRATEGY: unlike `block_branch_ops.py` (which tokenizes real git
subcommand argv via the shared `_lib.git_segments()` git-specific tokenizer),
`gcloud` is not git — there is no shared gcloud tokenizer in this codebase,
and building one is out of scope for what this gate needs. This module reuses
`_lib`'s GENERIC shell-command segmentation building blocks
(`_lib._split_segments` for compound-command splitting, `shlex.split` per
segment) and evaluates gcloud argv itself, mirroring `block_branch_ops.py`'s
own per-segment "first blocking segment wins" contract. The redirect/copy/move
ADC-file check runs on the RAW command text (mirroring
`block_head_overwrite.py`'s own raw-text redirect scan), since a shell
redirect is not a `gcloud` invocation at all and has no argv to tokenize as
one.

Parse-ambiguity fails CLOSED for a segment that mentions `gcloud` but cannot
be tokenized unambiguously — same posture as `block_branch_ops.py`'s
`untokenizable-segment-with-git`, for the identical reason: an untokenizable
wrapper is a trivially exploitable bypass shape if treated as "assume
harmless" instead.

CONTRACT (matching every other gate in this chain):
  * PURE decision function `decision(command) -> (block: bool, reason: str)`.
    No I/O, no env reads, no subprocess.
  * Thin `main()`: read event, decide, log always on a would-block, emit the
    canonical deny only when enforcing(). Always exits 0 — a deny is the JSON
    object, never an exit code.
  * CSA_DISABLE_HOOKS=1 master-OFF: no-op allow before anything else.
  * Escape hatch: CSA_ALLOW_GIT_STATE_OPS=1 in the hook's OWN process env lets
    a would-block through — reusing the SAME var `block_branch_ops.py`/
    `block_head_overwrite.py` already reserve for "an operator-only machine-
    state mutation, explicitly overridden for exactly one command" rather
    than minting a second name for what is the identical class of override.
    Any command STRING containing that literal is DENIED (agents must never
    smuggle it inline) — same tripwire, same reasoning, as every sibling gate.
  * Only the Bash tool is gated; every other tool is allowed.

The module never raises out to the caller: a crashing hook must never break
the agent. Every unexpected error degrades to ALLOW.
"""

