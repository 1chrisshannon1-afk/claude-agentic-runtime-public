    # (Task objects) -- both verb groups map to this one family/allowlist
    # (see `_DESCRIBE_VERB_GROUPS`/`_LIST_VERB_GROUPS`). ROUND 3 fix round,
    # item 5: the prior hint (`status.succeededcount`) is an EXECUTION-level
    # aggregate counter across all of an execution's tasks -- a single Task
