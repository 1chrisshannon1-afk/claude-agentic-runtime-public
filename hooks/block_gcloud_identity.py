# `nargs=0` flag is a real argparse error ("ignored explicit argument
# 'false'"), confirmed against the live installed CLI. `StoreTrueFalseAction`
# (`calliope/arg_parsers.py:2685`) is a DIFFERENT, unrelated action class
# used by other flags elsewhere in the SDK, never by `--log-http`.
