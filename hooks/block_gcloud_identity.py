# Nested command-text extraction (B2, #5890 round 4 fix
# round): a gcloud invocation can be hidden inside text this module's normal
# segment walk never inspects as ARGV at all -- a quoted `bash -c '...'`
# string, an `eval '...'` argument, a heredoc BODY fed to a shell
# interpreter, or a `$(...)`/backtick command-substitution SPAN that lives
# INSIDE a double-quoted token (`_split_segments` only treats `$(`/backtick
# as a segment boundary when `q is None` -- i.e. outside any open quote; see
# that function's own quote-state walk). Each of these is genuinely
# EXECUTED shell text, not inert data, so a gcloud call inside any of them is
# just as real as one typed directly on the command line.
# ---------------------------------------------------------------------------

# ROUND 6 (B3): widened from `{bash, sh, zsh}` to every common interpreter
# whose own `-c`/`--command`-style flag runs a string as a command --
# `bash -lc '...'` is the single most common agent idiom this module missed
# entirely pre-fix (login-shell + command, e.g. to pick up an rc file's
# PATH), and dash/ksh/mksh/fish/csh/tcsh all accept the identical shape.
_SHELL_INTERPRETER_BASENAMES = frozenset(
    {"bash", "sh", "zsh", "dash", "ksh", "mksh", "fish", "csh", "tcsh"}
)

# ROUND 6 (B3): matches any short-option CLUSTER that carries a `c` flag
# among other single-letter options -- `-c` itself, but also `-lc`, `-ec`,
# `-euxc`, `-xc`, etc. Real shells accept combining single-letter options
# into one token (`bash -lc CMD` == `bash -l -c CMD`), and whichever letter
# is `c` in the cluster is what takes the command-string ARGUMENT -- exactly
# like a bare `-c`. This is deliberately permissive (it also matches, e.g.,
# `-cl`, an unusual but equally valid ordering) rather than trying to
# enumerate every real flag combination each interpreter accepts, per this
# round's "simple, conservative, bounded" directive: a false-positive match
# here only means treating a token as carrying `-c` when it didn't (in which
# case the "next non-option argument" it extracts is inert data, not
# genuinely gcloud-invoking text -- functionally a no-op, not a new hole).
_DASH_C_CLUSTER_RE = re.compile(r"^-[A-Za-z]*c[A-Za-z]*$")

# Single-letter options accepted by `bash`/`sh`/`zsh`/... that themselves
# take a following argument the way `-c` does (only `-o`/`+o`, "set an
# option by name") -- needed so the "next non-option argument" walk (B3)
# correctly skips `-o OPTNAME`'s own value instead of mistaking it for the
# `-c` command string. `--` is handled separately (it marks "no more
# options" but is not itself skipped as an option's own value).
_INTERPRETER_VALUE_OPTIONS = frozenset({"-o", "+o"})


def _first_non_option_arg(argv: list[str], start: int) -> str | None:
    """Starting at `argv[start]`, return the first token that is genuinely
    an interpreter COMMAND-STRING argument (ROUND 6, B3), skipping:
      * a bare `--` (end-of-options marker; skipped, not returned, and does
        not itself count as the command string even though it is the
        conventional next token for `bash -c -- 'cmd'`);
      * an `-o OPTNAME` / `+o OPTNAME` pair (`_INTERPRETER_VALUE_OPTIONS`) --
        both the flag and its following value token are skipped together;
      * any other token that itself looks like an option (starts with `-`
        or `+` and is not just `-`/`+` alone) -- interpreters accept
        multiple option tokens before the command string
        (`bash -c -x -- 'cmd'` is not standard, but being permissive about
        skipping option-shaped tokens here only widens what this module
        can find, never narrows it, matching this round's fail-toward-
        detection bias).
    Returns the first token that survives all of the above, or None if
    `argv` is exhausted first. Never raises."""
    try:
        i = start
        n = len(argv)
        while i < n:
            tok = argv[i]
            if tok == "--":
                i += 1
                continue
            if tok in _INTERPRETER_VALUE_OPTIONS:
                i += 2
                continue
            if len(tok) > 1 and tok[0] in "-+":
                i += 1
                continue
            return tok
        return None
    except Exception:
        return None


def _extract_dash_c_body(seg_argv: list[str]) -> str | None:
    """If ANY token in `seg_argv` is a shell-interpreter program token
    (`_SHELL_INTERPRETER_BASENAMES`; bare, path-suffixed like `/bin/bash`,
    or reached past a shell keyword/wrapper such as `do bash -c '...'` --
    scanned like `_find_gcloud_argv`, not restricted to `seg_argv[0]`, for
    the identical reason: a shell keyword left as this segment's own leading
    text by `_split_segments` must not hide the interpreter invocation that
    follows it) carrying a `-c`-shaped flag (a bare `-c`/`--command`, OR any
    short-option CLUSTER containing `c`, e.g. `-lc`, `-euxc` -- ROUND 6, B3:
    real shells accept combining single-letter options into one token, and
    `bash -lc '...'` is the single most common agent idiom this module
    missed before this round), return the STRING argument taken by that
    flag -- the NEXT non-option token in the remaining argv, skipping `--`
    and an `-o OPTNAME`/`+o OPTNAME` pair (round 6: the earlier version only
    ever looked at the token immediately following an EXACT `-c`/
    `--command` token, so `bash -c -- '...'` extracted the literal string
    `--` instead of the real command, and `-lc`/`-euxc`-shaped clusters were
    never recognized as carrying `-c` at all).

    Returns None if no token in `seg_argv` is an interpreter invocation of
    this shape, or a `-c`-shaped flag was found but no command-string
    argument followed it. Never raises."""
    try:
        n = len(seg_argv)
        for start in range(n):
            prog = seg_argv[start].rsplit("/", 1)[-1]
            if prog not in _SHELL_INTERPRETER_BASENAMES:
                continue
            i = start + 1
            while i < n:
                tok = seg_argv[i]
                if tok == "-c" or tok == "--command":
                    return _first_non_option_arg(seg_argv, i + 1)
                if tok.startswith("--command="):
                    return tok[len("--command="):]
                if tok != "--" and not tok.startswith("--") and _DASH_C_CLUSTER_RE.match(tok):
                    # A short-option cluster containing `c` -- `-c` itself,
                    # or `-lc`/`-ec`/`-euxc`/etc. Either way, the command
                    # string is the NEXT non-option argument, never inline in
                    # this token (unlike `-cCOMMAND`, which real bash/sh also
                    # accept as a combined form -- but that shape is
                    # syntactically indistinguishable from a cluster ending
                    # in a non-flag-letter continuation, and treating it as
                    # "the whole rest of this token" when it's actually a
                    # cluster like `-lc` would be wrong; scanning the
                    # following tokens is correct for the common `-lc CMD`
                    # idiom this round exists to fix, and a real `-cCOMMAND`
                    # single-token form still gets caught by whatever
                    # gcloud-mentioning text it embeds via the raw-text
                    # substitution/heredoc scanners elsewhere in this
                    # module, which do not depend on argv shape at all).
                    return _first_non_option_arg(seg_argv, i + 1)
                i += 1
        return None
    except Exception:
        return None


def _extract_here_string_body(seg_argv: list[str]) -> str | None:
    """If ANY token in `seg_argv` is a shell-interpreter program token
    (`_SHELL_INTERPRETER_BASENAMES`, scanned the same way
    `_extract_dash_c_body` does) followed somewhere later by a HERE-STRING
    redirect (`<<<`, e.g. `bash <<< 'gcloud ...'`), return the joined
    remaining text as ONE string -- a here-string feeds its single
    word/string argument to the interpreter's STDIN exactly like `bash -c`
    feeds its argument as a command, so `bash <<< 'gcloud run services
    describe s'` is just as real an invocation as `bash -c '...'` (ROUND 6,
    B3).

    `_split_segments` deliberately does NOT treat `<<<` as a heredoc opener
    (it is a completely different construct -- a single inline word, never a
    multi-line body with its own terminator) and leaves it as ordinary
    token(s) in the segment's own argv, which is exactly why this needs no
    special raw-text extraction the way a real heredoc body does: `seg_argv`
    already contains the here-string's text verbatim (shlex-split, so outer
    quotes are already stripped).

    TWO shapes are handled, because `shlex.split` treats `<<<` differently
    depending on whether whitespace separates it from the quoted string that
    follows (round 6, same-round fix -- found by the reviewer's own c3.txt
    repro file, `bash <<<'...'` with no space, which the first version of
    this function silently missed):
      * `bash <<< 'gcloud ...'` (space after `<<<`) -- shlex produces `<<<`
        as its OWN token, followed by the (quote-stripped) string as the
        NEXT token(s). Joining everything after the exact `<<<` token
        reconstructs the fed text.
      * `bash <<<'gcloud ...'` (NO space after `<<<`) -- shlex has no
        special handling for `<<<` at all (it is not a real shell lexer), so
        it treats `<<<` and the immediately-following quoted text as ONE
        combined token, e.g. `<<<gcloud run services describe s`. Detected
        by a token that STARTS WITH `<<<` and is longer than just `<<<`
        itself; the text after the `<<<` prefix (plus any further tokens
        after it) is the fed text.

    Returns None if no token in `seg_argv` is an interpreter invocation
    followed by either `<<<` shape, or there is no text left to feed. Never
    raises."""
    try:
        n = len(seg_argv)
        for start in range(n):
            prog = seg_argv[start].rsplit("/", 1)[-1]
            if prog not in _SHELL_INTERPRETER_BASENAMES:
                continue
            for i in range(start + 1, n):
                tok = seg_argv[i]
                if tok == "<<<":
                    rest = seg_argv[i + 1 :]
                    if rest:
                        return " ".join(rest)
                    continue
                if tok.startswith("<<<") and len(tok) > 3:
                    inline = tok[3:]
                    rest = seg_argv[i + 1 :]
                    pieces = [inline] + rest if inline else rest
                    if pieces:
                        return " ".join(pieces)
                    continue
        return None
    except Exception:
        return None


def _extract_eval_body(seg_argv: list[str]) -> str | None:
    """If ANY token in `seg_argv` is the literal `eval` (scanned like
    `_extract_dash_c_body` above, for the identical "a shell keyword can
    precede it" reason), return the joined remaining arguments AFTER that
    token as ONE string (real shell `eval` re-tokenizes and concatenates ALL
    of its arguments with a single space before executing them as one
    command -- verified: `eval echo hi` and `eval 'echo hi'` behave
    identically). Returns None if no token in `seg_argv` is `eval`, or the
    match is `eval` with no arguments after it (nothing to extract). Never
    raises."""
    try:
        for i, tok in enumerate(seg_argv):
            if tok != "eval":
                continue
            rest = seg_argv[i + 1 :]
            if rest:
                return " ".join(rest)
        return None
    except Exception:
        return None


# ROUND 8 (B2): matches ANY heredoc opener -- quoted OR unquoted delimiter
# -- at the point it appears in raw text, with no requirement that it be
# anchored to a "segment end" the way `_HEREDOC_OPENER_ON_SEGMENT_RE`
# (used by `_extract_shell_heredoc_bodies`) is. `_all_heredoc_body_spans`
# below uses this to find every heredoc's own BODY span regardless of
# delimiter kind or interpreter-feeding, purely so `_single_quoted_spans`
# can jump over it -- a heredoc body is never real shell-quoted text (a
# `'`/`"` inside it is always a literal character, whether the delimiter is
# quoted or not), so no quote-tracking scan should ever open a "quote" on
# an apostrophe that lives inside one.
_ANY_HEREDOC_OPENER_RE = re.compile(
    r"<<-?\s*(?:(['\"])([A-Za-z_][A-Za-z0-9_]*)\1|([A-Za-z_][A-Za-z0-9_]*))"
)

# A hard ceiling on how many heredoc openers `_all_heredoc_body_spans` will
# examine in one call -- the same bounded-scan posture as
# `_MAX_HEREDOC_OPENERS_SCANNED` above (defined later in the module at
# import time, so this constant is intentionally its own, to avoid a
# forward-reference on a name defined further down in the file).
_MAX_HEREDOC_BODY_SPANS_SCANNED = 32


def _all_heredoc_body_spans(text: str) -> list[tuple[int, int]]:
    """Return every `[start, end)` BODY span of EVERY heredoc in `text`,
    quoted-delimiter or not, interpreter-fed or not (ROUND 8, B2) -- the
    complete opposite scoping from `_quoted_heredoc_skip_spans` (which
    covers only the quoted-AND-not-interpreter-fed subset, for a DIFFERENT
    purpose: deciding what `_extract_command_substitutions` must not
    recurse into). This function exists purely so `_single_quoted_spans`
    can jump over EVERY heredoc body when hunting for real single-quote
    spans, since NONE of them are ever real shell-quoted text regardless of
    delimiter kind.

    Bounded identically to `_extract_shell_heredoc_bodies`
    (`_MAX_HEREDOC_BODY_SPANS_SCANNED`) -- past the cap, this function
    simply stops looking for MORE openers and returns what it has found so
    far (never raises, never signals ambiguity of its own: it is a
    best-effort WIDENING helper for `_single_quoted_spans`, and that
    caller's OWN fail-closed behavior on an unterminated quote -- see its
    corrected docstring -- is what actually carries the safety obligation
    here, not this function).

    Never raises: an internal error returns whatever spans were found
    before the error (fail toward finding FEWER spans, never crashing)."""
    try:
        spans: list[tuple[int, int]] = []
        pos = 0
        n = len(text)
        openers_scanned = 0
        while pos < n:
            m = _ANY_HEREDOC_OPENER_RE.search(text, pos)
            if m is None:
                break
            openers_scanned += 1
            if openers_scanned > _MAX_HEREDOC_BODY_SPANS_SCANNED:
                break
            opener_start = m.start()
            line_end = text.find("\n", opener_start)
            if line_end == -1:
                # No body possible -- nothing left to scan either way.
                break
            delim = m.group(2) or m.group(3)
            tab_strip = text[opener_start : opener_start + 3] == "<<-"
            i = line_end + 1
            body_start = i
            found = False
            while i < n:
                nl = text.find("\n", i)
                le = n if nl == -1 else nl
                line = text[i:le]
                is_delim_line = (line.lstrip("\t") if tab_strip else line) == delim
                if is_delim_line:
                    spans.append((body_start, i))
                    pos = i
                    found = True
                    break
                i = le + 1
            if not found:
                # Unterminated heredoc -- nothing further to usefully scan.
                break
        return spans
    except Exception:
        return []


def _single_quoted_spans(text: str) -> list[tuple[int, int]]:
    """Return every `[start, end)` span of a SINGLE-quoted region in `text`
    (ROUND 6, P2-1; corrected ROUND 8, B2), scanning left to right and
    skipping the contents of any double-quoted region along the way (a `'`
    inside `"..."` is a literal character, never a quote opener -- real
    shell semantics).

    ROUND 8 CORRECTION (B2): the round-6 version had three real bugs, all
    found by the same class of repro (a prose apostrophe inside a heredoc
    body):
      1. It never skipped heredoc BODIES at all (of either delimiter kind)
         -- so a heredoc body's own prose apostrophe ("It's the deploy
         note", "fix: don't leak") was read as a REAL single-quote opener.
      2. It had no backslash-escape handling OUTSIDE quotes at all (only
         the double-quote branch escaped `\"`) -- real bash lets `\'`
         escape a literal apostrophe outside quotes (`echo don\'t`), and
         without that, an escaped apostrophe was ALSO misread as a real
         opener.
      3. Worst of all: an unterminated single-quote span (no matching
         close before the text ends -- exactly what (1)/(2) produced from
         a lone body/escaped apostrophe) extended its span to
         END-OF-TEXT -- so the false span didn't just mis-skip one
         character, it swallowed EVERYTHING after the apostrophe,
         including every later real `"$(gcloud ...)"` or backtick
         substitution in the command, which `_extract_command_
         substitutions` then never examined at all. Confirmed exploitable
         end-to-end: `cat > /tmp/notes.md <<'EOF'\nIt's the deploy
         note\nEOF\nX="$(gcloud config set account other@x.com)"` (and five
         other shapes across different heredoc/segment layouts) all
         silently ALLOWED a real identity mutation or unmasked describe.

      Fixed, in order:
      (a) heredoc bodies (`_all_heredoc_body_spans`, ANY delimiter kind) are
          jumped over WHOLESALE before this scan ever looks for a quote
          character inside one -- an apostrophe inside a heredoc body can
          never open a real quote span, so it is never even considered.
      (b) a backslash OUTSIDE any quote now escapes the next character
          (matching real bash: a backslash-quote outside quotes is a
          literal character,
          not quote operators) -- `echo don\'t` no longer misreads the
          escaped apostrophe as an opener.
      (c) If the scan reaches end-of-text while STILL inside an
          unterminated single-quote span, this function returns `[]` (fail
          CLOSED by returning NOTHING to skip, rather than fail-open by
          returning a span that swallows the rest of the text) -- an
          unterminated quote is itself a genuine ambiguity this function
          cannot safely resolve into "here is exactly what's inert," so the
          conservative answer is "skip nothing," which makes
          `_extract_command_substitutions` scan EVERYTHING, the same
          fail-toward-detection direction every other ambiguity in this
          module takes. This is a real behavior change from round 6 (which
          extended the span to end-of-text, i.e. skipped MORE, the WRONG
          direction for a security scanner) — round 6's own docstring
          claim that an internal error returns an empty list "the same
          `found nothing to skip` direction as a genuine absence" was
          already the correct PRINCIPLE; it just was not applied to this
          specific, very-reachable case.

    Double-quoted regions are still tracked and skipped over (their own `'`
    characters are never quote openers), with their own existing `\"`
    backslash-escape handling unchanged. Never raises: an internal error
    returns `[]` (the same fail-closed-by-skipping-nothing direction as
    (c) above -- a bug here can only widen what
    `_extract_command_substitutions` scans, never narrow it)."""
    try:
        heredoc_spans, heredoc_starts = _sorted_spans_with_starts(_all_heredoc_body_spans(text))
        spans: list[tuple[int, int]] = []
        i = 0
        n = len(text)
        while i < n:
            heredoc_end = _span_end_if_in_any(i, heredoc_spans, heredoc_starts)
            if heredoc_end is not None:
                i = heredoc_end
                continue
            c = text[i]
            if c == "\\" and i + 1 < n:
                # (b) a backslash OUTSIDE any quote escapes the next
                # character -- neither the backslash nor the escaped
                # character can open a quote.
                i += 2
                continue
            if c == '"':
                j = i + 1
                while j < n and text[j] != '"':
                    if text[j] == "\\" and j + 1 < n:
                        j += 2
                        continue
                    j += 1
                i = j + 1 if j < n else n
                continue
            if c == "'":
                start = i
                j = text.find("'", i + 1)
                if j == -1:
                    # (c) unterminated single quote -- fail CLOSED by
                    # reporting no spans at all, rather than extending this
                    # span (or any found so far) to swallow the rest of the
                    # text.
                    return []
                spans.append((start, j + 1))
                i = j + 1
                continue
            i += 1
        return spans
    except Exception:
        return []


def _quoted_heredoc_skip_spans(text: str) -> list[tuple[int, int]]:
    """Return every `[start, end)` BODY span of a heredoc whose delimiter is
    QUOTED (`<<'EOF'`/`<<\"EOF\"` -- a LITERAL body bash never expands) AND
    that is NOT fed to a shell interpreter (ROUND 6, P2-1) -- the exact
    complement of what `_extract_shell_heredoc_bodies` already extracts (that
    function returns the body of a quoted-delimiter heredoc ONLY when an
    interpreter consumes it, since only then is the body genuinely re-
    executed text). A heredoc body in THIS category is inert, non-executed
    file content (`git commit -F - <<'EOF' ... EOF`, `cat > msg <<'EOF' ...
    EOF`) -- any `$(...)`/backtick-shaped text inside it is literal
    characters being written to a file or piped as data, never a real
    command substitution, so `_extract_command_substitutions` must not
    descend into it.

    Reuses `_extract_shell_heredoc_bodies`'s own opener-detection regex
    (`_HEREDOC_OPENER_ON_SEGMENT_RE`) and interpreter-presence check so the
    two functions' notion of "fed to an interpreter" never drifts apart --
    this function's scan is a near mirror of that one, but instead of
    returning body text (destined for potential recursion) it returns the
    body's own SPAN (destined for exclusion). An UNQUOTED-delimiter heredoc
    (`<<EOF`, no interpreter needed) is never in this list -- bash expands
    substitutions inside such a body regardless of interpreter, so
    `_extract_command_substitutions`'s ordinary scan must still see it.

    Never raises (an internal error returns an empty list -- the same
    "nothing to skip" fail-toward-detection direction as
    `_single_quoted_spans`; the caller's OWN unmatched-opener handling is
    unaffected either way)."""
    try:
        spans: list[tuple[int, int]] = []
        openers_scanned = 0
        for m in re.finditer(r"<<-?\s*(?:['\"])[A-Za-z_][A-Za-z0-9_]*['\"]", text):
            openers_scanned += 1
            if openers_scanned > _MAX_HEREDOC_OPENERS_SCANNED:
                # P3-2: same bounded-scan posture as
                # `_extract_shell_heredoc_bodies` -- stop examining further
                # openers rather than risk the identical quadratic cost.
                # Fail-toward-detection here means STOP WIDENING the skip
                # list (any opener past the cap is simply not added, so
                # `_extract_command_substitutions`'s ordinary scan still
                # examines that later text -- never a silent new allow).
                break
            opener_start = m.start()
            is_quoted_delim = True  # the regex above only matches a quoted delimiter
            if not is_quoted_delim:
                continue
            frag_start = 0
            for boundary in (";", "&", "\n", "(", ")"):
                idx = text.rfind(boundary, 0, opener_start)
                if idx + 1 > frag_start:
                    frag_start = idx + 1
            line_end_probe = text.find("\n", opener_start)
            line_scan_end = len(text) if line_end_probe == -1 else line_end_probe
            opener_line = text[frag_start:line_scan_end]
            try:
                opener_line_argv = shlex.split(opener_line)
            except Exception:
                opener_line_argv = None
            interpreter_present = False
            if opener_line_argv is not None:
                for tok in opener_line_argv:
                    if tok.rsplit("/", 1)[-1] in _SHELL_INTERPRETER_BASENAMES:
                        interpreter_present = True
                        break
            else:
                interpreter_present = any(
                    re.search(r"(^|[^A-Za-z0-9_./])" + re.escape(name) + r"([^A-Za-z0-9_]|$)", opener_line)
                    for name in _SHELL_INTERPRETER_BASENAMES
                )
            if interpreter_present:
                # Fed to an interpreter -- `_extract_shell_heredoc_bodies`
                # already extracts and recurses into this body; do NOT also
                # add it to the skip list, or a real gcloud call hidden
                # inside it would be invisible to `_extract_command_
                # substitutions` while ALSO never being caught by that other
                # extractor's own `$(...)` handling (that function returns
                # raw body text for further recursion, not for THIS
                # function's own `$(...)`  scan -- skipping it here would be
                # a silent double-gap, not a redundancy).
                continue
            mm = _HEREDOC_OPENER_ON_SEGMENT_RE.search(text[frag_start : opener_start + len(m.group(0))])
            if not mm:
                continue
            delim = mm.group(2) or mm.group(3)
            tab_strip = text[opener_start : opener_start + 3] == "<<-"
            line_end = text.find("\n", opener_start)
            if line_end == -1:
                continue
            i = line_end + 1
            body_start = i
            n = len(text)
            while i < n:
                nl = text.find("\n", i)
                le = n if nl == -1 else nl
                line = text[i:le]
                is_delim_line = (line.lstrip("\t") if tab_strip else line) == delim
                if is_delim_line:
                    spans.append((body_start, i))
                    break
                i = le + 1
        return spans
    except Exception:
        return []


def _in_any_span(pos: int, spans: list[tuple[int, int]]) -> bool:
    """True iff `pos` falls inside any `[start, end)` span in `spans`.
    Linear in the number of spans, which is always small (bounded by the
    number of quotes/heredocs in one command). Never raises.

    Kept for callers that only need the boolean (and for backward-
    compatible readability) -- a scanning loop that advances `pos` one
    character at a time and calls this every step should prefer
    `_span_end_if_in_any` instead (ROUND 7, P3-c) so it can jump directly to
    the covering span's end rather than re-querying every position inside
    it."""
    try:
        return any(start <= pos < end for start, end in spans)
    except Exception:
        return False


def _sorted_spans_with_starts(
    spans: list[tuple[int, int]],
) -> tuple[list[tuple[int, int]], list[int]]:
    """Sort `spans` by start position ONCE, and return `(sorted_spans,
    starts)` -- `starts` is `sorted_spans`' own start positions as a
    separate list, precomputed once so `_span_end_if_in_any` never has to
    rebuild it on every call (ROUND 8, P3-c). Call this ONCE per scanning
    loop, before the loop begins, and pass BOTH return values into every
    `_span_end_if_in_any` call inside that loop. Never raises: an internal
    error returns `(spans, [])`, which makes every subsequent
    `_span_end_if_in_any` call safely return `None` (falls back to the
    caller's own single-character-advance path)."""
    try:
        ordered = sorted(spans, key=lambda sp: sp[0])
        return ordered, [s for s, _e in ordered]
    except Exception:
        return (spans, [])


def _span_end_if_in_any(pos: int, sorted_spans: list[tuple[int, int]], starts: list[int]) -> int | None:
    """If `pos` falls inside any `[start, end)` span in `sorted_spans`
    (SORTED BY START, with `starts` its own precomputed start-position list
    -- both produced ONCE by `_sorted_spans_with_starts` before the caller's
    scanning loop begins, never rebuilt here), return that span's own `end`
    (so a scanning caller can jump straight there instead of re-testing
    every intervening position) -- else return `None` (ROUND 7, P3-c;
    corrected ROUND 8, P3, for the ACTUAL complexity claim).

    ROUND 7's own claim ("the overall scan becomes O(len(text) +
    len(spans))") was FALSE, found in round 8's cold review: the ORIGINAL
    round-7 implementation did a plain LINEAR scan over `spans` on EVERY
    call, including every call for a position that is NOT inside any span
    (the common case -- most of the text is outside a quote/heredoc span).
    So the cost was still O(len(spans)) PER CALL, and the caller calls this
    once per un-skipped character position, giving the identical
    O(len(text) * len(spans)) total the round-6 `_in_any_span` scan already
    had -- round 7's fix jumped over the INSIDE of a span in O(1) once
    detected, but never reduced the cost of DETECTING whether a given
    position is inside one in the first place, which is where nearly all
    of the actual work happens on realistic input (most characters are
    outside any span).

    ROUND 8 FIX: uses `bisect.bisect_right` over the CALLER-precomputed
    sorted starts to find the single CANDIDATE span in O(log len(spans))
    instead of scanning every span, and does NOT re-sort or re-derive
    `starts` on each call (that would still cost O(len(spans) log
    len(spans)) per call, worse than the round-7 bug it replaces) --
    sorting happens exactly ONCE per scan, in `_sorted_spans_with_starts`.
    Spans in this module's ACTUAL combined use never overlap -- but this is
    only true because of a specific dependency between two functions, not a
    self-evident structural fact, so it is spelled out precisely here
    rather than asserted (round-8 correction: a prior version of this
    comment asserted non-overlap as an unconditional structural given,
    which understated what actually makes it true). `_single_quoted_spans`
    (round 8, B2) explicitly jumps over every `_all_heredoc_body_spans`
    span BEFORE ever considering a character a quote opener, so it can
    NEVER produce a single-quoted span that starts inside any heredoc body
    (quoted-delimiter or not) -- the only way a single-quoted span can
    start is on a real quote character OUTSIDE every heredoc body, e.g. a
    heredoc's own `<<'DELIM'` opener syntax, whose quoted-delimiter span
    ends strictly BEFORE the body itself begins (on the next line).
    `_quoted_heredoc_skip_spans` in turn only ever returns BODY spans
    (never opener-syntax spans), which start strictly after the delimiter
    line, so it can never start inside a single-quoted span either. Given
    that dependency holds, at most ONE span can ever contain `pos`, and
    bisecting on start position alone is sufficient to find it (the
    candidate is the LAST span whose start is `<= pos`; checking only that
    one span's own `end` is enough) -- but that soundness is contingent on
    `_single_quoted_spans` continuing to skip heredoc bodies; a future
    change to either function must re-verify this property, not assume it.
    This makes each call O(log len(spans)) regardless of whether `pos` is
    inside a span or not, so the overall scan is genuinely
    O(len(text) * log(len(spans)) + len(spans) log(len(spans))) (the sort
    happens once) -- not the exact O(len(text) + len(spans)) round 7
    claimed, but a real, substantial improvement over the
    O(len(text) * len(spans)) both round 6 and the ACTUAL round-7
    implementation had. This is not a general-purpose interval-membership
    utility, only what this module's own callers need (non-overlapping
    spans, no need to handle multiple candidate spans). Never raises: an
    internal error returns `None` (the caller then falls back to its own
    single-character-advance path, which is always correct, just
    potentially slower on a bug)."""
    try:
        if not starts:
            return None
        idx = bisect.bisect_right(starts, pos) - 1
        if idx < 0:
            return None
        start, end = sorted_spans[idx]
        if start <= pos < end:
            return end
        return None
    except Exception:
        return None


# Balanced-span extraction for `$(...)` and backtick `` `...` `` command
# substitution, scanning the RAW command text directly (not per-segment
# argv) -- this is the only way to reach a substitution that lives INSIDE a
# double-quoted token, which `_split_segments` deliberately treats as inert
# quoted text rather than a segment boundary (correct for its own job: the
# quotes are real shell syntax, and gcloud's OWN segment walk needs the
# quoted string as one token) but wrong for finding EXECUTED text nested
# inside it. A backtick span nested inside `$(...)` (or vice versa) is
# resolved by depth-tracking each opener independently; an unterminated
# opener (no matching close before the string ends) is reported via the
# `ambiguous` return so the caller can fail closed exactly like every other
# untokenizable shape in this module.
def _extract_command_substitutions(text: str) -> tuple[list[str], bool]:
    """Scan `text` for every `$(...)` and backtick-delimited command
    substitution span, at any nesting depth and REGARDLESS of the OUTER
    DOUBLE-quote state (deliberately -- see module comment above: a
    substitution living inside a double-quoted token is still executed), and
    return (list of each span's INNER text, ambiguous).

    ROUND 6 CORRECTION (P2-1): the prior version of this scanner ignored
    the outer quote state ENTIRELY, including single quotes -- but bash
    NEVER expands `$(...)`/backticks inside single quotes, so scanning
    inside them was a real over-block (`grep '$(gcloud run services
    describe' docs/`, `printf '...$(gcloud run services describe s)...'`
    -- neither ever executes anything). It also had no concept of a heredoc
    body at all, so a LITERAL (quoted-delimiter) heredoc body fed to
    something OTHER than a shell interpreter (`git commit -F - <<'EOF'
    ...backtick-quoted markdown mentioning a covered command... EOF`, `cat >
    msg <<'EOF' ...`, or this very issue's own `gh issue comment --body
    "$(cat <<'EOF' ...EOF)"` idiom) is inert file content bash never
    executes -- scanning inside it for `$(...)`/backticks was denying an
    idiom the runtime's own commit-message and issue-comment conventions
    rely on.

    Fixed by pre-computing two kinds of SKIP region before the scan starts:
    `_single_quoted_spans` (every single-quoted span, itself double-quote-
    aware so a `'` inside `"..."` is correctly NOT treated as a quote
    opener) and `_quoted_heredoc_skip_spans` (every literal heredoc body NOT
    fed to an interpreter). A `$(`/backtick opener whose position falls
    inside either kind of span is skipped entirely -- not merely its
    contents, the OPENER ITSELF, so a single-quoted `$(...)`-shaped
    substring is never even considered a real opener. Scanning still
    proceeds normally through double-quoted regions and unquoted-delimiter
    heredoc bodies (bash DOES expand inside both), and the balanced-span
    depth walk for a genuine, non-skipped opener is UNCHANGED from the prior
    version (still quote-aware for quoting that occurs INSIDE the span
    itself -- see below).

    The `$(...)` depth walk is QUOTE-AWARE for quoting that occurs INSIDE
    the span itself: a `'`/`"` opens a nested quoted region whose own `)`
    characters do NOT count toward the paren depth (matching real shell
    semantics -- `$(gcloud ... --format='value(name)')` closes at the FINAL
    `)`, not at the one embedded inside the quoted `--format` value). Without
    this, a literal `)` inside a quoted gcloud `--format` projection value
    like `value(name)` was misread as the substitution's own closing paren,
    truncating the extracted inner text and corrupting it into an
    unparseable fragment (confirmed: an earlier version of this scanner
    produced `"gcloud ... --format='value(name"` -- an unterminated single
    quote -- from exactly this shape).

    `ambiguous=True` means a NON-SKIPPED opener (`$(` or a backtick) was
    found with no matching close before the string ended (including a quote
    opened inside the span that itself never closes) -- the caller treats
    this as a fail-closed signal, mirroring `_gcloud_segments`' own
    untokenizable-segment handling. An unterminated single quote or
    unterminated quoted-heredoc delimiter at the OUTER level does NOT by
    itself make this function return ambiguous -- `_gcloud_segments`'s own
    segment walk (via `_lib._split_segments`) is what fails closed on
    genuinely malformed outer shell syntax; this function's job is narrower
    (find real nested substitutions), so an outer-level quoting oddity that
    this function's own span helpers tolerate (extending an unterminated
    single quote to end-of-string, or an unmatched heredoc delimiter simply
    not being added to the skip list) is not re-litigated here. Never raises
    (an internal error returns `([], True)` -- the same fail-closed
    direction as a genuine unmatched opener, never silently `([], False)`,
    since a caller-side exception here is itself an ambiguity this module
    cannot resolve, not evidence of safety)."""
    try:
        # ROUND 7 (P2-a): `_quoted_heredoc_skip_spans` is computed ONCE
        # against the FULL `text` and reused by BOTH the outer scan and the
        # inner `$(...)` depth walk below -- see that walk's own comment for
        # why it needs this too, not merely the outer loop.
        heredoc_skip_spans_raw = _quoted_heredoc_skip_spans(text)
        heredoc_skip_spans, heredoc_skip_starts = _sorted_spans_with_starts(heredoc_skip_spans_raw)
        skip_spans, skip_starts = _sorted_spans_with_starts(
            _single_quoted_spans(text) + heredoc_skip_spans_raw
        )
        out: list[str] = []
        i = 0
        n = len(text)
        while i < n:
            span_end = _span_end_if_in_any(i, skip_spans, skip_starts)
            if span_end is not None:
                # P3-c: jump straight to the span's end instead of
                # re-testing every position inside it one at a time.
                i = span_end
                continue
            if text[i : i + 2] == "$(":
                depth = 1
                j = i + 2
                start = j
                q: str | None = None
                while j < n and depth > 0:
                    # ROUND 7 CORRECTION (P2-a): the prior version of this
                    # inner walk had NO notion of `_quoted_heredoc_skip_
                    # spans` at all -- only the OUTER loop (above) checked
                    # them, so a `$(...)` substitution whose OWN inner text
                    # contains a literal (quoted-delimiter) heredoc body NOT
                    # fed to an interpreter (`$(cat <<'EOF' ... EOF)`, this
                    # runtime's own `gh issue comment` idiom) still had its
                    # body scanned character-by-character HERE, where a lone
                    # apostrophe inside that body's PROSE ("It's fixed: ...")
                    # was misread as opening a real shell quote (`q = "'"`)
                    # that then never closed before the substitution's own
                    # closing `)`, making `depth` never reach 0 and this
                    # whole command fail closed as `untokenizable-segment-
                    # with-gcloud` -- denying the runtime's OWN completion-
                    # comment convention whenever the comment text happened
                    # to contain an apostrophe before the first stray `)`.
                    # Fixed by jumping straight past a heredoc-skip span the
                    # SAME way the outer loop does, WITHOUT touching `q` --
                    # the span's own content is inert (never bash-expanded,
                    # by construction of `_quoted_heredoc_skip_spans`), so it
                    # must not be allowed to open OR close a quote state that
                    # would otherwise persist past the span's own end.
                    # P3-c: jump straight to the span's end rather than
                    # re-testing every position inside it.
                    heredoc_span_end = _span_end_if_in_any(j, heredoc_skip_spans, heredoc_skip_starts)
                    if heredoc_span_end is not None:
                        j = heredoc_span_end
                        continue
                    c = text[j]
                    if q:
                        if c == q:
                            q = None
                        j += 1
                        continue
                    if c in ("'", '"'):
                        q = c
                        j += 1
                        continue
                    if text[j : j + 2] == "$(":
                        depth += 1
                        j += 2
                        continue
                    if c == ")":
                        depth -= 1
                        j += 1
                        continue
                    j += 1
                if depth > 0:
                    return (out, True)
                out.append(text[start : j - 1])
                i = j
                continue
            if text[i] == "`":
                j = text.find("`", i + 1)
                if j == -1:
                    return (out, True)
                out.append(text[i + 1 : j])
                i = j + 1
                continue
            i += 1
        return (out, False)
    except Exception:
        return ([], True)


# Heredoc body fed to a shell interpreter (`bash <<'EOF' ... EOF`, `cat
# <<'EOF' | bash ... EOF`, or any interpreter in `_SHELL_INTERPRETER_BASENAMES`
# reading its heredoc directly): `_split_segments` DROPS a literal
# (quoted-delimiter) heredoc body outright as inert redirected input (correct
# for gcloud's OWN segment walk -- see that function's own docstring), but a
# body fed into a shell interpreter's stdin is genuinely EXECUTED text, not
# inert data, so it must still be recursively inspected. Scoped narrowly: an
# interpreter segment (its own program token is `bash`/`sh`/`zsh`, from
# `_extract_dash_c_body`'s same basename set) carrying a `<<DELIM`/`<<'DELIM'`
# opener on ITS OWN segment text is exactly the shape `_split_segments`
# leaves behind (the opener's line becomes its own segment; see that
# function's docstring) -- this extractor re-scans the ORIGINAL raw command
# text starting right after that segment's own heredoc opener, for the
# matching close-delimiter line, and returns everything in between.
_HEREDOC_OPENER_ON_SEGMENT_RE = re.compile(
    r"<<-?\s*(?:(['\"])([A-Za-z_][A-Za-z0-9_]*)\1|([A-Za-z_][A-Za-z0-9_]*))\s*$"
)

# ROUND 6 (P3-2): a hard ceiling on how many REAL heredoc bodies
# `_extract_shell_heredoc_bodies` will consume-and-skip-past in one call.
# Real commands have at most a handful of heredocs, so this ceiling is well
# above any legitimate use, but it bounds an adversarial input (thousands of
# distinct heredoc openers) to a small, fixed amount of work. Past the
# ceiling, this function stops scanning and reports `ambiguous=True` for the
# remainder of the command -- fail CLOSED, matching this module's posture on
# every other case where it gives up trying to soundly parse something, per
# this round's "bounded, not cleverer parsing" directive.
_MAX_HEREDOC_OPENERS_SCANNED = 32


def _extract_shell_heredoc_bodies(command: str) -> tuple[list[str], bool]:
    """Find every heredoc whose body is fed to a shell interpreter, and
    return (list of each such heredoc's raw BODY text, ambiguous). Works
    directly against the raw command string (not `_gcloud_segments`, which
    already dropped these bodies) by locating each `<<[-]DELIM`/
    `<<[-]'DELIM'`/`<<[-]"DELIM"` opener, then checking whether the
    interpreter appears ANYWHERE on that opener's own LINE (from the nearest
    preceding control-operator-ish boundary through end-of-line) -- covering
    both the direct-read shape (`bash <<'EOF'`, interpreter is the heredoc's
    own reader) and the PIPED shape (`cat <<'EOF' | bash`, interpreter is
    the pipe TARGET receiving the heredoc's stdout as its own stdin -- the
    common "feed a script to bash via a pipe fed by a heredoc" idiom). A
    plain substring/whole-word scan for an interpreter basename on that line
    is deliberately used here rather than a full argv walk (unlike
    `_extract_dash_c_body`'s token-position-aware scan) -- this function
    only needs to know an interpreter is SOMEWHERE on the line consuming
    this heredoc, not which flags it was given, so a coarser check is
    sufficient and avoids re-deriving pipe topology this module has no
    tokenizer for. Scans forward for the matching close-delimiter line
    exactly like `_lib._split_segments`'s own heredoc consumption does
    (tab-stripped for the `<<-` form). `ambiguous=True` on an opener with no
    matching close-delimiter line before the string ends.

    ROUND 6 (P3-2): the scan now ADVANCES `i` MANUALLY (a `while` loop over
    positions, not `re.finditer` over the whole string) so that once a REAL
    heredoc opener's body has been located, the scan resumes AFTER that
    body -- never re-scanning INSIDE it for more `<<`-shaped text. This is
    both a correctness fix and the perf fix: the prior `re.finditer` walk
    matched every `<<`-shaped substring ANYWHERE in the command, including
    ones that are just literal characters inside an already-consumed
    heredoc's own body text (e.g. a commit-message-style heredoc body that
    itself contains the literal text "x << y" many times) -- each such
    in-body match did cheap-but-nonzero work (a `shlex.split` of its own
    "line"), and at large body sizes this was the real quadratic driver
    (measured: 3,000 such in-body `<<`-shaped substrings took ~14s). Once a
    real heredoc's body span is known, jumping past it removes those
    spurious matches entirely rather than merely capping how many of them
    get examined -- so a single large, legitimate heredoc (one real opener,
    however many `<<`-shaped substrings its OWN body text happens to
    contain) costs ONE unit of work, never one per spurious in-body match,
    and `_MAX_HEREDOC_OPENERS_SCANNED` now genuinely bounds the number of
    DISTINCT heredocs in a command, not the number of `<<`-shaped substrings
    anywhere in it (the former is what a real command's heredoc COUNT looks
    like; the latter is what an adversarial input can pad arbitrarily).
    Never raises (an internal error returns `([], True)`, the fail-closed
    direction, for the same reason `_extract_command_substitutions` does)."""
    try:
        out: list[str] = []
        openers_scanned = 0
        pos = 0
        n_total = len(command)
        opener_re = re.compile(r"<<-?\s*(?:['\"]?[A-Za-z_][A-Za-z0-9_]*['\"]?)")
        while pos < n_total:
            m = opener_re.search(command, pos)
            if m is None:
                break
            openers_scanned += 1
            if openers_scanned > _MAX_HEREDOC_OPENERS_SCANNED:
                # P3-2: too many opener candidates to soundly (and cheaply)
                # evaluate -- fail closed for the remainder rather than
                # continue the expensive per-opener scan.
                return (out, True)
            opener_start = m.start()
            # The segment this opener belongs to: everything since the last
            # control-operator-ish boundary before it. A conservative,
            # local re-scan (not a full `_split_segments` re-entry) is
            # enough here.
            frag_start = 0
            for boundary in (";", "&", "\n", "(", ")"):
                idx = command.rfind(boundary, 0, opener_start)
                if idx + 1 > frag_start:
                    frag_start = idx + 1
            # The opener's own LINE, extended through the next newline (or
            # end of string) so a pipe target AFTER the opener on the same
            # line (`cat <<'EOF' | bash`) is included in the scan, not just
            # the text before the opener.
            line_end_probe = command.find("\n", opener_start)
            line_scan_end = len(command) if line_end_probe == -1 else line_end_probe
            opener_line = command[frag_start:line_scan_end]
            try:
                opener_line_argv = shlex.split(opener_line)
            except ValueError:
                opener_line_argv = None
            except Exception:
                opener_line_argv = None
            interpreter_present = False
            if opener_line_argv is not None:
                for tok in opener_line_argv:
                    if tok.rsplit("/", 1)[-1] in _SHELL_INTERPRETER_BASENAMES:
                        interpreter_present = True
                        break
            else:
                # The line didn't shlex cleanly (e.g. the delimiter's own
                # quoting) -- fall back to a bare whole-word scan of the
                # same line text rather than skipping this opener outright,
                # matching this function's own fail-toward-detection bias.
                interpreter_present = any(
                    re.search(r"(^|[^A-Za-z0-9_./])" + re.escape(name) + r"([^A-Za-z0-9_]|$)", opener_line)
                    for name in _SHELL_INTERPRETER_BASENAMES
                )
            mm = _HEREDOC_OPENER_ON_SEGMENT_RE.search(command[frag_start : opener_start + len(m.group(0))])
            if mm is None:
                # Not a real heredoc opener shape at all (e.g. `x << y`, a
                # bare shift-left-looking fragment with no valid delimiter
                # ending the "line" scanned) -- this cannot start a real
                # heredoc body either, so simply resume scanning right after
                # this match, exactly as before (no body to jump past).
                pos = opener_start + len(m.group(0))
                continue
            delim = mm.group(2) or mm.group(3)
            tab_strip = command[opener_start : opener_start + 3] == "<<-"
            # Body starts at the newline right after the opener match. This
            # IS a real heredoc opener (matched `_HEREDOC_OPENER_ON_SEGMENT_RE`)
            # regardless of whether it's interpreter-fed -- find its body
            # span EITHER WAY, so the outer scan can jump past it (round 6:
            # this is what stops a legitimate large heredoc body's own
            # in-text `<<`-shaped substrings from ever being re-examined as
            # candidate openers, the actual quadratic-cost fix).
            line_end = command.find("\n", opener_start)
            if line_end == -1:
                # No body possible (nothing after the opener's own line) --
                # ROUND 7 CORRECTION (P3-b): this used to `break`, ending
                # the WHOLE scan -- but this opener having no line after it
                # says nothing about earlier text; it only means THIS
                # opener candidate has no body to find. Advance `pos` past
                # this match and keep scanning (there is nothing further
                # ahead of `opener_start` in the string either way, since
                # `line_end == -1` means this was the last line, so this is
                # a loop-exit in practice, but expressed as a resumable
                # `continue` rather than an unconditional `break` for the
                # same reason the other case below now is -- consistency,
                # and no cost, since the while condition (`pos < n_total`)
                # will end the loop naturally once `pos` reaches the end).
                pos = opener_start + len(m.group(0))
                continue
            i = line_end + 1
            body_start = i
            found = False
            n = len(command)
            while i < n:
                nl = command.find("\n", i)
                le = n if nl == -1 else nl
                line = command[i:le]
                is_delim_line = (line.lstrip("\t") if tab_strip else line) == delim
                if is_delim_line:
                    if interpreter_present:
                        out.append(command[body_start:i])
                    found = True
                    pos = i  # resume scanning AT the closing delimiter line,
                    # not past it -- a `&&`/`;`/pipe target trailing on that
                    # SAME line (e.g. `cat <<'EOF' | bash\n...\nEOF; gcloud
                    # ...`) must still be scanned for further openers.
                    break
                i = le + 1
            if not found:
                # An opener with no matching close-delimiter line before the
                # string ends. Ambiguous ONLY when this heredoc is
                # interpreter-fed (a real, unterminated EXECUTED body this
                # module cannot fully account for) -- an unterminated
                # heredoc fed to something else (a redirect target, `cat`,
                # etc.) is inert either way, and `_lib._split_segments`'s own
                # segment walk is what governs whether the OUTER command is
                # itself well-formed; this function's job is narrower (find
                # executed nested text), so it does not re-litigate that
                # here.
                if interpreter_present:
                    return (out, True)
                # ROUND 7 CORRECTION (P3-b): a non-interpreter-fed opener
                # with no matching close used to `break`, ending the WHOLE
                # scan -- so a LATER, genuinely dangerous heredoc anywhere
                # after this false opener in the command was never examined
                # at all. Repro: `echo $((1<<b))` (the `1<<b` arithmetic
                # shift is not a real heredoc opener, has no closing
                # delimiter, and is not interpreter-fed) followed on the
                # NEXT line by `cat <<'EOF' | bash\ngcloud run services
                # describe s\nEOF` -- a real, interpreter-fed heredoc that
                # genuinely needs examining -- was previously never reached:
                # the scan stopped dead at the FIRST, harmless false opener.
                # Fixed by resuming the scan right after this match instead
                # of ending it, exactly like the `mm is None` branch above
                # already does for a differently-shaped non-opener.
                pos = m.end()
                continue
        return (out, False)
    except Exception:
        return ([], True)


def _env_var_assignment_or_removal_is_active(command: str, var_name: str) -> bool:
    """Raw-text scan of `command` for every shape that SETS or REMOVES the
    named env var (`var_name`), and returns whether the var must be treated
    as resolving to a TRUTHY value SOMEWHERE in this command (P3-2, round 4
    fix round; rewritten round 6, B2) -- the mitigation-form counterpart of
    the raw-text tripwires that call this
    (`CLOUDSDK_CORE_LOG_HTTP`/`CLOUDSDK_CORE_FORMAT`).

    ROUND 6 CORRECTION (B2): the prior version of this function resolved
    "LAST occurrence in the text wins" -- intended to get `unset VAR; VAR=1;
    gcloud ...` right (the later assignment correctly wins), but it also
    silently ALLOWED the opposite, equally real "set, run, clean up" shape:
    `export VAR=1; gcloud ...; unset VAR` -- an ordinary debugging pattern.
    Read textually left-to-right, the trailing `unset` is the LAST event, so
    the old rule resolved the whole command to "inactive" and allowed it
    straight through -- even though the gcloud call embedded in the middle
    ran while the var was genuinely set, and gcloud's own HTTP-body dump
    happens at THAT moment, not at the end of the shell script. This module
    has no shell interpreter and cannot determine true execution order
    across segments/subshells/`&&`/`;`, so "last occurrence wins" was never
    a sound ordering proxy in the first place -- it happened to get one
    shape right and silently got its mirror image wrong.

    The round-6 fix drops any attempt at ordering and instead asks a
    strictly simpler, BOUNDED, and fail-closed question, per this round's own
    design directive ("prefer simple, conservative, bounded rules over more
    parsing"): is there ANY truthy assignment (or unrecognized mention)
    ANYWHERE in the command? If so, the var is treated as ACTIVE regardless
    of where any unset/removal also appears -- a later cleanup does not
    retroactively make an earlier real gcloud invocation safe. The var is
    treated as INACTIVE (safe) only when EVERY recognized occurrence in the
    command is itself a removal or a falsy assignment:

      * `VAR=value` (assignment, any shape: bare prefix, `export VAR=value`,
        inside `env VAR=value ...`) -- TRUTHY unless `value` is one of
        `_FALSE_FLAG_VALUES` (false/no/0), matching `--log-http=false`'s own
        accepted spellings (P3-1: gcloud itself would reject that exact
        spelling on the FLAG, but this function scores the ENV VAR form,
        which properties.py reads as a plain string and does accept these
        spellings as falsy -- see `_FALSE_FLAG_VALUES`'s own docstring).
      * `unset VAR` -- a removal (safe on its own).
      * `env -u VAR` / `env --unset VAR` (env's own removal flag) -- a
        removal (safe on its own).
      * `VAR` appearing with NONE of the above shapes (e.g. only ever
        referenced in text, or the tripwire's own raw-substring check
        already confirmed the literal string is present but this scan finds
        no assignment/removal shape at all -- a bare mention with no `=`) --
        treated as an unrecognized-but-present mention, which counts as
        TRUTHY (fail toward denying, matching every other parse-ambiguity
        posture in this module: an unrecognized shape is never silently
        treated as safe).

    ROUND 7 CORRECTION (P2-b): the round-6 version of this function
    contradicted its OWN docstring above, in both directions, because it
    only ever recorded TRUTHY assignments and removals into its two
    tracking collections, then asked a single BLANKET "did I recognize
    ANYTHING at all in this whole command" question before falling through
    to "any truthy position makes it truthy" -- neither half of that
    actually implements "count every occurrence, treat an occurrence not
    covered by a recognized shape as truthy":
      (1) A FALSY assignment (`VAR=0`) was never added to EITHER
          collection -- so a command whose ONLY occurrence of the var was a
          safe falsy assignment (`CLOUDSDK_CORE_LOG_HTTP=0 gcloud projects
          list`) had `has_any_recognized_shape` come back False (nothing
          was ever recorded for it) and fell into the "no recognized shape,
          fail toward denying" branch -- wrongly TRUTHY, the opposite of
          what the docstring above promises for a falsy assignment.
      (2) The "has ANY recognized shape anywhere" gate meant that the
          presence of a removal ANYWHERE in the command (e.g. a trailing
          `unset VAR`) made `has_any_recognized_shape` True, after which the
          function returned `bool(truthy_positions)` -- which is EMPTY, and
          therefore False, whenever the command's only OTHER occurrence of
          the var was an UNRECOGNIZED bare mention (`export VAR` with no
          `=`, `read VAR <<< 1`, `: ${VAR:=1}`) rather than a truthy
          assignment. So `export CLOUDSDK_CORE_LOG_HTTP; gcloud ...; unset
          CLOUDSDK_CORE_LOG_HTTP` -- a bare `export` (which, in real bash,
          exports whatever the variable's CURRENT value already is, doing
          nothing to set it to anything in particular, and is therefore
          exactly the "I cannot determine what this does" case the
          docstring says must count as truthy) -- was wrongly resolved
          SAFE, attacker-shaped: an agent could genuinely leave the var
          resolving to an inherited/ambient value this module has no way to
          rule out as truthy, disguised behind a same-command `unset` that
          never actually undoes anything a bare `export` did.

    Fixed by tracking occurrences PER-POSITION instead of two blanket
    collections: every occurrence of `var_name` as a whole word is found
    first (`re.finditer` on the bare name), then each occurrence's position
    is classified by checking whether it falls inside the SPAN of a
    recognized truthy-assignment, falsy-assignment, or removal match found
    separately. An occurrence whose position is not covered by any of the
    three recognized-shape regexes is UNRECOGNIZED and counts as truthy,
    exactly matching the docstring's own "any occurrence not covered by a
    recognized assignment or removal is truthy" rule. The var is truthy
    (this function returns True) iff ANY occurrence -- assignment, removal,
    or unrecognized -- resolves truthy; safe (False) only when EVERY single
    occurrence in the command is itself a removal or a falsy assignment.

    Never raises: an internal error returns True (fail toward denying, the
    same direction as every ambiguous case above)."""
    try:
        mentions = list(re.finditer(r"\b" + re.escape(var_name) + r"\b", command))
        if not mentions:
            # The caller only reaches this function when its own raw-text
            # substring check already confirmed the literal string is
            # present -- a `\b`-bounded re-scan finding nothing is itself an
            # ambiguity (e.g. the substring appeared only as part of a
            # longer identifier the caller's own substring check still
            # matched -- unlikely given the caller's own check, but fail
            # toward denying rather than assuming safety either way).
            return True

        # Recognized TRUTHY-assignment spans: `VAR=value` (any shape: bare
        # prefix, `export VAR=value`, inside `env VAR=value ...`) where
        # `value` is NOT one of `_FALSE_FLAG_VALUES`.
        truthy_spans: list[tuple[int, int]] = []
        # Recognized FALSY-assignment spans: the identical shape, but
        # `value` IS one of `_FALSE_FLAG_VALUES` -- P2-b: these must be
        # recorded as their OWN recognized-safe category, not silently
        # dropped the way the round-6 version left them.
        falsy_spans: list[tuple[int, int]] = []
        # `var_name` is wrapped in its OWN capture group (group 1) so the
        # span recorded below is the NAME's own position, not the match's
        # start -- the match can start earlier, at an optional leading
        # `export\s+` (ROUND 7 fix: the prior version used `m.start()`
        # directly, which is WRONG whenever `export` precedes the name,
        # silently mis-recording the span 7+ characters before the actual
        # mention it was meant to cover -- verified: this made every
        # `export VAR=value` assignment's OWN mention position fall
        # OUTSIDE its own recorded span, so it was misclassified as an
        # unrecognized mention instead of the assignment it actually is).
        for m in re.finditer(
            r"(?:\bexport\s+)?\b(" + re.escape(var_name) + r")=([^\s;&|]*)",
            command,
        ):
            value = m.group(2).strip("'\"")
            span = (m.start(1), m.end(1))
            if value.strip().lower() not in _FALSE_FLAG_VALUES:
                truthy_spans.append(span)
            else:
                falsy_spans.append(span)

        # Recognized REMOVAL spans: `unset VAR` or `env -u VAR`/
        # `env --unset VAR`.
        removal_spans: list[tuple[int, int]] = []
        for m in re.finditer(r"\bunset\s+" + re.escape(var_name) + r"\b", command):
            removal_spans.append((m.start(), m.end()))
        for m in re.finditer(
            r"\benv\s+(?:[A-Za-z_][A-Za-z0-9_]*=\S+\s+)*(?:-u|--unset)[= ]"
            + re.escape(var_name)
            + r"\b",
            command,
        ):
            removal_spans.append((m.start(), m.end()))

        for mention in mentions:
            pos = mention.start()
            if any(start <= pos < end for start, end in truthy_spans):
                return True
            if any(start <= pos < end for start, end in falsy_spans):
                continue
            if any(start <= pos < end for start, end in removal_spans):
                continue
            # Not covered by any recognized shape -- an unrecognized
            # mention (bare `export VAR` with no `=`, `read VAR <<< ...`,
            # `: ${VAR:=...}`, or any other shape this module does not
            # enumerate). Fail toward denying: this occurrence's actual
            # effect on the variable's value cannot be determined, so it is
            # treated as truthy, matching the docstring's own rule.
            return True

        # Every single occurrence was covered by a falsy assignment or a
        # removal -- genuinely safe.
        return False
    except Exception:
        return True


def _mentions_gcloud_anywhere(command: str, depth: int = 0) -> bool:
    """True iff `command` invokes `gcloud` as a program EITHER at the
    top level (`_mentions_gcloud`'s own program-token scan) OR anywhere
    inside a nested `bash -c`/`eval` argument, heredoc body fed to a shell
    interpreter, or `$(...)`/backtick command-substitution span (B2, round 4
    fix round) -- the same nested-text universe
    `_decision_segments_and_nested` extracts and recurses into for the main
    block/allow decision, reused here so the `CLOUDSDK_CORE_LOG_HTTP`
    raw-text tripwire's own "does this command actually invoke gcloud
    somewhere" gate has the identical reach. Without this, `export
    CLOUDSDK_CORE_LOG_HTTP=1; bash -c 'gcloud run services list'` -- a real
    incident shape -- passed the OLD `_mentions_gcloud` gate (its top-level
    program token is `bash`, not `gcloud`) and skipped the tripwire
    entirely, even though the nested `bash -c` argument genuinely invokes
    gcloud under the exact env var this tripwire exists to catch.

    Depth-capped identically to `_decision_segments_and_nested` (same
    `_MAX_NESTED_EXTRACTION_DEPTH`) -- past the cap, unexamined nested text
    is conservatively treated as IF it mentions gcloud (fail toward firing
    the tripwire, matching every other parse-ambiguity posture in this
    module). Never raises: an internal error returns True (fail toward
    firing the tripwire, the same direction as every other error case in
    this function)."""
    try:
        if depth > _MAX_NESTED_EXTRACTION_DEPTH:
            return True
        if _mentions_gcloud(command):
            return True
        try:
            command_mentions_gcloud_text = bool(_GCLOUD_WORD_RE.search(command))
        except Exception:
            return True
        if not command_mentions_gcloud_text:
            return False

        nested_texts: list[str] = []
        try:
            segments = _lib._split_segments(command)
        except Exception:
            segments = []
        for seg in segments:
            try:
                seg_argv = shlex.split(seg)
            except Exception:
                continue
            dash_c = _extract_dash_c_body(seg_argv)
            if dash_c is not None:
                nested_texts.append(dash_c)
            eval_body = _extract_eval_body(seg_argv)
            if eval_body is not None:
                nested_texts.append(eval_body)
            here_string = _extract_here_string_body(seg_argv)
            if here_string is not None:
                nested_texts.append(here_string)

        subs, subs_ambiguous = _extract_command_substitutions(command)
        if subs_ambiguous:
            return True
        nested_texts.extend(subs)

        heredocs, heredocs_ambiguous = _extract_shell_heredoc_bodies(command)
        if heredocs_ambiguous:
            return True
        nested_texts.extend(heredocs)

        return any(
            _mentions_gcloud_anywhere(text, depth + 1) for text in nested_texts if text and text.strip()
        )
    except Exception:
        return True


# Recursion depth cap for nested command-text extraction (B2, round 4 fix
# round) -- `_decision_segments_and_nested` calls itself for each extracted
# `bash -c`/`eval`/heredoc/`$(...)`/backtick body, which can in principle
# nest arbitrarily (`bash -c 'bash -c "bash -c ..."'`). Six levels is far
# beyond any real agent-authored command this module has ever seen and still
# bounds the cost of a pathological/adversarial input to a small constant --
# hitting the cap degrades to treating the innermost unexamined text as
# `untokenizable` (fail CLOSED, never silently allowed), mirroring this
# module's posture on every other parse-ambiguity case.
_MAX_NESTED_EXTRACTION_DEPTH = 6


def _decision_segments_and_nested(command: str, depth: int) -> tuple[bool, str]:
    """The segment-walk core of `decision()` (step 5 in its docstring),
    factored out so it can recurse into nested command text (B2, round 4 fix
    round) -- a `bash -c '...'`/`eval '...'` argument, a heredoc body fed to
    a shell interpreter, or a `$(...)`/backtick command-substitution span
    (including one nested inside a double-quoted token, which the segment
    walk itself never opens as its own segment -- see
    `_extract_command_substitutions`'s own module comment). Each is
    genuinely EXECUTED shell text, so a gcloud call hidden inside any of
    them is exactly as real as one on the top-level command line.

    Depth-capped at `_MAX_NESTED_EXTRACTION_DEPTH` -- past the cap, further
    nested text is treated as an unexamined, gcloud-mentioning-capable
    ambiguity and fails CLOSED (`untokenizable-segment-with-gcloud`) rather
    than silently allowed, matching this module's fail-closed posture on
    every other parse-ambiguity case.

    ROUND 6 CORRECTION (P3-3): this docstring previously claimed "any
    internal error here degrades to (False, '') for the offending nested
    text specifically, never propagating past this function's own
    try/except" -- that was FALSE. This function has NO top-level
    try/except of its own (unlike its sibling extractors, each of which
    does catch its own errors and report them via their own `ambiguous`
    return). Each EXTRACTION step here (`_gcloud_segments`,
    `_lib._split_segments`, `shlex.split` per segment,
    `_extract_command_substitutions`, `_extract_shell_heredoc_bodies`) is
    individually guarded by its OWN try/except, either inline here or
    inside that extractor itself -- but the RECURSIVE call at the bottom of
    this function (`_decision_segments_and_nested(text, depth + 1)`, in the
    `for text in nested_texts` loop below) is NOT wrapped in a try/except of
    its own. An exception raised inside that recursive call (or inside any
    of the extraction calls that ARE guarded, if the guard itself somehow
    fails to catch it) propagates straight up through every recursion level
    and out of this function entirely, to be caught only by `decision()`'s
    own OUTER try/except -- which fails OPEN (`decision-error`, allow) for
    the WHOLE command, not merely for the one nested text that triggered it.
    This is the same fail-open-on-internal-bug posture every other function
    in this module documents for ITS OWN internal errors; the prior
    docstring's claim of finer-grained, per-nested-text degradation was
    simply never true of the code.
    """
    if depth > _MAX_NESTED_EXTRACTION_DEPTH:
        return (True, "untokenizable-segment-with-gcloud")

    for seg_argv, untokenizable in _gcloud_segments(command):
        if untokenizable:
            return (True, "untokenizable-segment-with-gcloud")
        block, reason = _evaluate_gcloud_argv(seg_argv)
        if block:
            return (True, reason)

    # ---- Nested command text (B2) --------------------------------------
    # Only worth extracting from text that plausibly hides a gcloud call
    # SOMEWHERE -- deliberately the cheap raw whole-word substring check
    # (`_GCLOUD_WORD_RE`), NOT `_mentions_gcloud`'s program-token-aware scan:
    # the entire point of this block is to find a gcloud invocation
    # `_mentions_gcloud`'s own top-level program-token check CANNOT see
    # (because the segment's own program is `bash`/`eval`/etc., not
    # `gcloud`, until its ARGUMENT is extracted and recursed into) -- so
    # gating on `_mentions_gcloud` here would always evaluate False for
    # every nested shape this block exists to catch, defeating it entirely.
    # A false positive here (the substring "gcloud" appears in inert text
    # with no real invocation anywhere, nested or not) only costs a wasted
    # extraction pass that then finds nothing to recurse into -- cheap, and
    # the correct direction to err.
    try:
        command_mentions_gcloud_text = bool(_GCLOUD_WORD_RE.search(command))
    except Exception:
        command_mentions_gcloud_text = True
    if not command_mentions_gcloud_text:
        return (False, "no-gcloud-identity-mutation")

    nested_texts: list[str] = []

    try:
        segments = _lib._split_segments(command)
    except Exception:
        segments = []
    for seg in segments:
        try:
            seg_argv = shlex.split(seg)
        except ValueError:
            continue
        except Exception:
            continue
        dash_c = _extract_dash_c_body(seg_argv)
        if dash_c is not None:
            nested_texts.append(dash_c)
        eval_body = _extract_eval_body(seg_argv)
        if eval_body is not None:
            nested_texts.append(eval_body)
        here_string = _extract_here_string_body(seg_argv)
        if here_string is not None:
            nested_texts.append(here_string)

    subs, subs_ambiguous = _extract_command_substitutions(command)
    if subs_ambiguous:
        return (True, "untokenizable-segment-with-gcloud")
    nested_texts.extend(subs)

    heredocs, heredocs_ambiguous = _extract_shell_heredoc_bodies(command)
    if heredocs_ambiguous:
        return (True, "untokenizable-segment-with-gcloud")
    nested_texts.extend(heredocs)

    for text in nested_texts:
        if not text or not text.strip():
            continue
        block, reason = _decision_segments_and_nested(text, depth + 1)
        if block:
            return (block, reason)

    return (False, "no-gcloud-identity-mutation")


def decision(command: str) -> tuple[bool, str]:
    """Pure policy: should this Bash command be blocked? -> (block, reason).

    Mirrors `block_branch_ops.decision()`'s exact shape and precedence:
      1. Empty/whitespace command                          -> allow.
      2. The literal ESCAPE_VAR anywhere in the string      -> BLOCK (tripwire).
      3. A raw-text ADC-file-write shape (redirect/cp/mv/tee onto
         application_default_credentials.json)             -> BLOCK.
      4. The literal string CLOUDSDK_CORE_LOG_HTTP anywhere in a command that
         also mentions gcloud (any assignment SHAPE: `export X=1;`, `env
         X=1`, a bare `X=1` prefix in a DIFFERENT shell segment than the
         gcloud call, `set -a; X=1; set +a;`, ...)          -> BLOCK.
      5. Otherwise inspect every shell command segment (RECURSING, as of B2
         round 4 fix round, into any `bash -c`/`eval` argument, heredoc body
         fed to a shell interpreter, or `$(...)`/backtick command
         substitution span found anywhere in the command -- see
         `_decision_segments_and_nested`); the FIRST segment or nested text
         that is a blocked gcloud identity-mutation blocks the whole line
         (covers compound `a && gcloud ...`, pipes, subshells, and now
         wrapped/nested gcloud invocations too).
      6. No blocking segment or nested text                 -> allow.

    Does NOT consult env, does NOT decide log-only-vs-enforce, does NOT honor
    the escape hatch — those are main()'s job (mirroring every sibling gate).
    Never raises: any error degrades to (False, ...) so the guard fails OPEN
    on its own bugs — except the documented fail-CLOSED cases below,
    matching block_branch_ops.py's own posture.
    """
    try:
        if not command or not command.strip():
            return (False, "empty-command")

        if ESCAPE_VAR in command:
            return (True, "inline-escape-var-forbidden")

        adc_reason = _find_adc_overwrite(command)
        if adc_reason:
            return (True, adc_reason)

        # ---- CLOUDSDK_CORE_LOG_HTTP anywhere, any assignment shape (B5) ----
        # A per-segment leading-env-prefix check alone (the kind
        # `_evaluate_gcloud_argv`'s `_has_log_http` performs for the
        # `--log-http` FLAG) only catches a LEADING env-prefix token on the
        # SAME segment as the gcloud invocation
        # (`CLOUDSDK_CORE_LOG_HTTP=1 gcloud ...`). This module used to also
        # carry a dedicated `_has_cloudsdk_core_log_http_env` helper for that
        # narrower same-segment shape -- removed in the round 3 fix round
        # (item 5) as genuinely unreachable dead code once THIS raw-text
        # check (below) always fires first for any command it would also
        # catch. A command that sets the var in a DIFFERENT shell segment
        # first --
        # `export CLOUDSDK_CORE_LOG_HTTP=1; gcloud ...`, `env
        # CLOUDSDK_CORE_LOG_HTTP=1 gcloud ...` (env's own leading-assignment
        # form, not a leading-token-on-the-gcloud-segment form),
        # `set -a; CLOUDSDK_CORE_LOG_HTTP=1; set +a; gcloud ...` -- reaches the
        # identical property (properties.py reads `CLOUDSDK_<SECTION>_<NAME>`
        # from the process environment, not from argv position) with no argv
        # shape this gate's per-segment gcloud tokenizer would ever see on the
        # gcloud segment itself. Mirrors the ESCAPE_VAR tripwire immediately
        # above: a raw substring match across the WHOLE command string, not
        # scoped to one shlex-tokenized segment, for the identical reason --
        # an env assignment's shell shape is unbounded (any command that can
        # set a variable in the calling shell/subshell works), so this is
        # checked as a raw-text substring rather than enumerated per shape.
        # Scoped to a command that also ACTUALLY INVOKES `gcloud` as a
        # program (`_mentions_gcloud_anywhere`, WIDENED in the B2 round 4 fix
        # round from `_mentions_gcloud`'s top-level-only program-token check
        # to also recurse into nested `bash -c`/`eval`/heredoc/`$(...)`/
        # backtick text -- see that function's own docstring for the exact
        # incident shape this closes: `export CLOUDSDK_CORE_LOG_HTTP=1; bash
        # -c 'gcloud run services list'` has a top-level program token of
        # `bash`, not `gcloud`, so the narrower check missed it even though
        # the nested `bash -c` argument genuinely invokes gcloud) so a
        # command that merely references this env var's NAME in text -- a
        # `grep`/`cat` of this module's own source, a pytest `-k
        # CLOUDSDK_CORE_LOG_HTTP` selector, a file literally named
        # `gcloud.log` -- is never denied just for mentioning the string.
        # This is NOT the same claim as "any command containing the
        # substring gcloud is never denied" -- a command that DOES invoke
        # gcloud (in any segment OR nested text, per
        # `_mentions_gcloud_anywhere`'s own scan) alongside this env var
        # anywhere in the text is still denied here exactly as before; only
        # the FALSE-POSITIVE case (the substring appears with no real gcloud
        # invocation anywhere, nested or not) is what this gate skips.
        # P3-2 (round 4 fix round): the raw-text tripwire above used to fire
        # on the bare presence of the substring, which also denied the
        # MITIGATION forms (`unset CLOUDSDK_CORE_LOG_HTTP`, `env -u
        # CLOUDSDK_CORE_LOG_HTTP gcloud ...`) that clear the exact hazard
        # this tripwire exists to catch -- `_env_var_assignment_or_removal_
        # is_active` resolves whether the var is truthy anywhere in the
        # text. STALE COMMENT FIXED (round 8, P3): this used to say
        # "LAST-occurrence-wins" -- that was the round-6 semantics, REPLACED
        # in round 7 (P2-b) because it silently allowed "set, run gcloud,
        # clean up" (`export VAR=1; gcloud ...; unset VAR`), since the
        # trailing unset read as the textually-last event even though the
        # gcloud call genuinely ran with the var set. The ACTUAL, current
        # rule (see that function's own docstring): truthy if ANY occurrence
        # in the text is a truthy assignment or an unrecognized mention;
        # safe ONLY when EVERY occurrence is a removal or a falsy
        # assignment -- a pure unset/`-u` removal, with no truthy occurrence
        # anywhere else in the text, correctly allows; a truthy assignment
        # anywhere, even alongside a later unset, correctly still denies.
        if (
            "CLOUDSDK_CORE_LOG_HTTP" in command
            and _mentions_gcloud_anywhere(command)
            and _env_var_assignment_or_removal_is_active(command, "CLOUDSDK_CORE_LOG_HTTP")
        ):
            return (True, "log-http-leaks-response")

        # ---- CLOUDSDK_CORE_FORMAT anywhere (P3-1) --------------------------
        # The env-var counterpart of `config set format`/`core/format`
        # immediately above -- same raw-text-substring-across-the-whole-
        # command posture as the CLOUDSDK_CORE_LOG_HTTP tripwire, for the
        # identical reason (an env assignment's shell shape is unbounded).
        # See `_FORMAT_PROPERTY_NAMES`'s own comment for why this is denied
        # defensively even though it is UNVERIFIED as exploitable on the
        # currently-installed SDK. Same P3-2 unset/`-u` mitigation-form
        # allowance as CLOUDSDK_CORE_LOG_HTTP above.
        if (
            "CLOUDSDK_CORE_FORMAT" in command
            and _mentions_gcloud_anywhere(command)
            and _env_var_assignment_or_removal_is_active(command, "CLOUDSDK_CORE_FORMAT")
        ):
            return (True, "format-env-override")

        return _decision_segments_and_nested(command, 0)
    except Exception:
        # A bug in the decision core must not crash the hook; fail OPEN.
        return (False, "decision-error")


# ---------------------------------------------------------------------------
# Generic shell-command segmentation (compound commands: &&, ||, ;, |, \n).
#
# gcloud has no shared tokenizer in this codebase the way git does
# (`_lib.git_segments`), so this reuses `_lib`'s lower-level, git-agnostic
# splitter (`_lib._split_segments`, the same quote-aware boundary walk
# `block_branch_ops.py`'s own `_lib.git_segments` is built on) and applies a
# plain `shlex.split` per segment — no git-specific global-option stripping
# needed, since gcloud's own global flags (--account, etc.) are exactly what
# `_evaluate_gcloud_argv` already scans for positionally.
# ---------------------------------------------------------------------------


def _gcloud_segments(command: str) -> list[tuple[list[str], bool]]:
    """Split `command` into shell segments and shlex-tokenize each.

    Returns a list of (argv, untokenizable) pairs, ONE PER SEGMENT WHOSE
    PROGRAM TOKEN IS `gcloud` (`_mentions_gcloud`, #5890
    round 3 fix round item 2 -- tightened from a bare whole-word TEXT match
    to an actual program-token check). STALE COMMENT FIXED (round 8, P3):
    this used to describe `_mentions_gcloud` as walking past a leading
    env-assignment/`env`/`sudo`/`command`/`exec` wrapper -- that was the
    round-3 mechanism, REPLACED in round 4's B2 fix by scanning EVERY token
    in the segment's argv for the first one that IS a gcloud program token
    (`_find_gcloud_argv`, via `_segment_program_mentions_gcloud`), with no
    fixed wrapper list at all (see `_find_gcloud_argv`'s own docstring for
    why the fixed-list approach was replaced: `time`, `timeout N`,
    `nohup`, `xargs`, and shell keywords like `do`/`then` all walked
    straight past the old fixed list). A segment whose program is not
    gcloud (including one that merely mentions the word "gcloud" in a
    path, flag value, or comment-like text) is dropped
    entirely (nothing to evaluate, and no fail-closed concern: a segment
    whose own program token is provably not gcloud can't itself BE a gcloud
    command, though see `_mentions_gcloud`'s docstring for the untokenizable
    fallback below). `untokenizable=True` means the segment's program token
    could not be determined AT ALL because `shlex.split` itself raised
    (unbalanced quoting) and `_mentions_gcloud`'s own fallback whole-word
    check on that unparseable text found "gcloud" anyway — the caller treats
    that as a block candidate (fail CLOSED), mirroring `block_branch_ops.py`'s
    identical `\\x00untokenizable` sentinel handling for the same reason: an
    untokenizable wrapper around a dangerous verb is a bypass shape, not an
    innocuous parse quirk.

    Never raises: any internal error yields [] (degrades to allow via the
    caller's `for` loop simply not running), matching every sibling gate's
    fail-open contract EXCEPT the two documented fail-closed reasons handled
    by the caller.
    """
    try:
        segments = _lib._split_segments(command)
    except Exception:
        return []
    out: list[tuple[list[str], bool]] = []
    for seg in segments:
        if not _mentions_gcloud(seg):
            continue
        try:
            argv = shlex.split(seg)
        except ValueError:
            out.append(([], True))
            continue
        out.append((argv, False))
    return out


_GCLOUD_WORD_RE = re.compile(r"(^|[^A-Za-z])gcloud([^A-Za-z]|$)")


def _segment_program_mentions_gcloud(segment: str) -> bool:
    """True iff this ONE already-control-operator-free shell segment
    actually invokes `gcloud` ANYWHERE in its tokens, per the shared
    `_find_gcloud_argv` helper (B2, round 4 fix round -- see that function's
    own docstring for why a scan-every-token approach replaced the old fixed
    wrapper-token walk: it needed no `env`/`sudo`/`command`/`exec` allowlist,
    and unlike that allowlist, it also covers `time`, `timeout N`, `nohup`,
    `xargs [...]`, and shell keywords like `do`/`then`/`else`/`{`/`!` that
    `_split_segments` can legitimately leave as a segment's own leading
    token or text with no enumeration needed here at all). Shlex-tokenizes
    just this segment; falls back to the conservative whole-word substring
    match on a tokenize failure (fail CLOSED -- see `_mentions_gcloud`'s
    docstring for why). Never raises."""
    try:
        argv = shlex.split(segment)
    except ValueError:
        try:
            return bool(_GCLOUD_WORD_RE.search(segment))
        except Exception:
            return False
    except Exception:
        return False
    try:
        return _find_gcloud_argv(argv) is not None
    except Exception:
        return False


def _mentions_gcloud(segment: str) -> bool:
    """True iff `segment` -- one shell segment OR a full, possibly compound,
    multi-segment command string -- actually INVOKES `gcloud` as a program
    somewhere in it, not merely a substring/whole-word TEXT mention
    (#5890 round 3 fix round, item 2). The prior
    implementation matched the bare whole word "gcloud" ANYWHERE in the text
    (`_GCLOUD_WORD_RE`, bounded only by non-ASCII-alpha characters, i.e.
    `_`/`.`/digits/whitespace/punctuation all count as boundaries) -- so a
    file path or flag VALUE merely naming this module
    (`hooks/block_gcloud_identity.py`, `gcloud.log`, a pytest `-k
    CLOUDSDK_CORE_LOG_HTTP` selector run from this test file's own name) was
    indistinguishable from an actual `gcloud` invocation, and combined with
    the CLOUDSDK_CORE_LOG_HTTP raw-substring check at the top of `decision()`
    (which itself never invokes gcloud), a plain `grep`/`cat`/`pytest -k`
    command that merely referenced this env var's name in text was denied
    outright -- a real false positive an agent has no way to route around.

    This function has callers with different input shapes, all of which it
    must serve correctly (function names, not line numbers -- line numbers
    drift with every edit and have gone stale here before; see P3-5, round 4
    fix round; the bullet below was ITSELF stale until round 6, P3-3 --
    corrected to match the actual call graph rather than re-asserting the
    same style of claim unchecked):
      * `_gcloud_segments` calls it on ONE segment already split out of a
        larger command by `_lib._split_segments`.
      * `_mentions_gcloud_anywhere` (round 4 fix round, B2) calls it as its
        OWN first check before falling through to nested-text extraction --
        this function alone never looks inside a `bash -c`/`eval`/heredoc/
        `$(...)`/backtick body; `_mentions_gcloud_anywhere` is the function
        that widens the search into those nested shapes, and IS what the
        raw-text tripwires (`CLOUDSDK_CORE_LOG_HTTP`/`CLOUDSDK_CORE_FORMAT`)
        call instead of this function directly, for exactly that reason.

    ROUND 6 CORRECTION (P3-3): a prior version of this docstring claimed
    `_decision_segments_and_nested` also calls THIS function on the whole
    command string. That was never true of the code: `_decision_segments_
    and_nested`'s own nested-text pre-check uses the cheaper
    `_GCLOUD_WORD_RE.search(command)` whole-word TEXT match directly (see
    that function's own comment for why: it deliberately does NOT want the
    program-token-aware check here, since the entire point of that block is
    to find a gcloud invocation hidden behind a NON-gcloud top-level program
    token like `bash`/`eval`, which THIS function's own top-level-program
    scan would always miss). `decision()` itself is the one that reaches the
    `export CLOUDSDK_CORE_LOG_HTTP=1; gcloud run services list` shape this
    bullet used to describe -- via `_mentions_gcloud_anywhere`, not via a
    direct call to this function from `_decision_segments_and_nested`.
    So this function ALWAYS re-splits its input into control-operator-
    delimited segments first (idempotent when given an already-single
    segment: `_lib._split_segments` on text with no `&&`/`;`/`|`/newline
    returns a single-element list containing that same text back), then
    returns True iff ANY resulting segment's own program token
    (`_segment_program_mentions_gcloud`) is `gcloud`. A split failure falls
    back to the whole-word substring match on the ORIGINAL, unsplit text --
    fail CLOSED, matching `_gcloud_segments`' own posture of treating an
    untokenizable-but-gcloud-mentioning segment as a block candidate rather
    than silently allowing. Never raises."""
    try:
        segments = _lib._split_segments(segment)
    except Exception:
        try:
            return bool(_GCLOUD_WORD_RE.search(segment))
        except Exception:
            return False
    try:
        return any(_segment_program_mentions_gcloud(seg) for seg in segments)
    except Exception:
        return False


def _raw_mentions_gcloud(raw: str) -> bool:
    """Fail-closed "does this untokenizable/unparseable raw text carry a real
    gcloud invocation" check, used ONLY on `main()`'s JSON-parse-error path
    (#5890 round 3 fix round, item 2) -- `raw` there is
    stdin content that failed to parse as the expected hook-event JSON at
    all, so there is no shell command to tokenize in the first place and no
    program-token walk to perform; this deliberately stays the OLD
    whole-word substring match (mirroring `block_branch_ops._raw_mentions_git`'s
    own top-level parse-error use, which is the same conservative shape for
    the identical reason) rather than attempting `_mentions_gcloud`'s
    tokenize-and-walk, which has nothing valid to walk here."""
    try:
        return bool(_GCLOUD_WORD_RE.search(raw))
    except Exception:
        return False


# ---------------------------------------------------------------------------
# ADC-file-write detection: a shell redirect/cp/mv/tee onto the well-known
# Application Default Credentials path. Modeled directly on
# block_head_overwrite.py's raw-text regex approach for the identical reason:
# a shell redirect is not a `gcloud` invocation and has no argv to tokenize
# as one, so this scans the RAW command text rather than any segment argv.
# ---------------------------------------------------------------------------

# The ADC filename itself — matched as a path SUFFIX (any leading directory
# component, `~`-relative, `$HOME`-relative, or a bare filename in a `cd`'d
# context all count) rather than requiring the exact canonical absolute path,
# since an agent could just as easily target it via `~/.config/gcloud/...` or
# a relative form after `cd ~/.config/gcloud`.
_ADC_FILENAME = "application_default_credentials.json"

# `> file`, `>> file`, `>|file`, `N>file` (redirect operators) immediately
# followed (allowing whitespace) by a path ending in the ADC filename.
_ADC_REDIRECT_RE = re.compile(
    r"\d*(?:>>|>\||>)\s*([^\s;&|]*" + re.escape(_ADC_FILENAME) + r")"
)

# Programs whose LAST path-shaped argument is a copy/move-style destination
# (`cp SRC DEST`, `mv SRC DEST`, `ln [-s] SRC DEST`, `install SRC DEST`,
# `rsync SRC DEST`) — a directory destination is handled separately below,
# since for these the ADC filename comes from the SOURCE side instead.
_ADC_LAST_ARG_DEST_PROGS = frozenset({"cp", "mv", "ln", "install", "rsync"})


def _segment_writes_adc_via_cp_mv_tee(seg_argv: list[str], seg: str) -> bool:
    """True iff a file-copy/move/link/write-style segment's own argv writes
    to a path ending in the ADC filename — directly (an explicit destination
    filename ending in `application_default_credentials.json`) or indirectly
    (copying/moving/linking/installing/syncing a source FILE NAMED
    `application_default_credentials.json` into a DIRECTORY destination,
    which preserves the source's basename at the destination).

    `cp`/`mv`/`ln`/`install`/`rsync SRC DEST`: the destination is the LAST
    non-flag argument.
      * If DEST itself ends in the ADC filename -> match (direct rename/copy
        onto the exact ADC path).
      * If DEST is directory-SHAPED (ends in `/`, OR its basename carries no
        `.`-delimited extension distinguishing it from a directory name --
        `cp /tmp/application_default_credentials.json ~/.config/gcloud`, no
        trailing slash, is a real, common spelling: the destination is an
        existing directory and cp/mv/install/rsync all place the file inside
        it exactly as the trailing-slash form does) and any SOURCE argument's
        basename is the ADC filename -> match (the well-known filename
        survives the copy into that directory unchanged). A dest basename
        WITH a `.`-extension (e.g. `key.json`, `backup.tar.gz`) is treated as
        a genuine destination FILENAME, not a directory, so this never
        misfires on an ordinary renamed-copy destination.
    `tee [-a] DEST [DEST...]`: every non-flag argument after the command name
    is a destination (tee can write multiple files) — any one of them ending
    in the ADC filename is a match.

    Known over-block, not silent: the extensionless-directory-destination
    heuristic above also matches a READ *out of* the ADC file, not just a
    write onto it — `cp ~/.config/gcloud/application_default_credentials.json
    /tmp/mybackup` (SOURCE is the ADC file; DEST has no `.`-extension) is
    itself a directory-shaped destination by this same rule, so it blocks
    even though it never mutates the shared ADC file at all, only reads it.
    This is a deliberate, accepted false positive, not a bug: distinguishing
    "SRC is the ADC file" (harmless copy-out) from "a SOURCE argument's
    basename is the ADC file and DEST looks like a directory" (the real
    bypass this function exists to catch) would require knowing which
    argument is genuinely the ADC path versus an incidental one, which this
    purely positional, no-filesystem-access detection cannot determine either
    way — and failing SAFE (occasionally over-blocking a benign read) is the
    correct trade against failing OPEN (missing a real write-in). The
    escapable per-command scoping this gate already reserves for the operator
    (the `CSA_ALLOW_GIT_STATE_OPS` escape hatch) covers the rare legitimate
    need to read ADC out to a directory this way.

    Never raises: an argv that shlex can't split simply yields no match here
    (the redirect-regex path below still catches the common `> file` shape
    independently).
    """
    if not seg_argv:
        return False
    prog = seg_argv[0].rsplit("/", 1)[-1]
    args = [a for a in seg_argv[1:] if not a.startswith("-")]
    if not args:
        return False
    if prog in _ADC_LAST_ARG_DEST_PROGS:
        # A genuine SRC DEST invocation of these programs always carries >= 2
        # positional args. A lone positional arg is not a copy/move/link at
        # all for any of these programs (e.g. a bare `ln -s target` with no
        # explicit link name -- it creates a link in the CWD named after the
        # source's own basename, never a caller-chosen destination), so it
        # can never be a write onto the ADC path via this detection and is
        # excluded up front rather than only from the directory-destination
        # branch below.
        if len(args) < 2:
            return False
        dest = args[-1]
        if dest.endswith(_ADC_FILENAME):
            return True
        # Directory-destination form: `cp /tmp/key.json ~/.config/gcloud/`
        # (trailing slash) or `cp /tmp/key.json ~/.config/gcloud` (no
        # trailing slash, but DEST's own basename has no file-extension shape
        # -- an existing-directory destination is a routine spelling agents
        # use without the trailing slash) both keep the source's own
        # basename at the destination.
        dest_basename = dest.rstrip("/").rsplit("/", 1)[-1]
        looks_like_directory = dest.endswith("/") or "." not in dest_basename
        if looks_like_directory:
            sources = args[:-1]
            return any(src.rsplit("/", 1)[-1] == _ADC_FILENAME for src in sources)
        return False
    if prog == "dd":
        # `dd if=SRC of=DEST` — GNU/BSD `dd` uses `key=value` pseudo-flags,
        # not positional args or `-`-prefixed flags, so this checks the
        # `of=` argument directly rather than the generic flag-stripping
        # above (which would otherwise treat `of=...` as a non-flag
        # positional, which happens to still work here, but `of=` is the
        # only argument that matters for this check regardless of position).
        for a in seg_argv[1:]:
            if a.startswith("of=") and a[len("of=") :].endswith(_ADC_FILENAME):
                return True
        return False
    if prog == "tee":
        return any(a.endswith(_ADC_FILENAME) for a in args)
    return False


def _find_adc_overwrite(command: str) -> str | None:
    """Scan `command` for a shell-level write to the ADC file path. Returns a
    reason string on a match, else None. Never raises."""
    try:
        if _ADC_REDIRECT_RE.search(command):
            return "adc-file-redirect-write"
        try:
            segments = _lib._split_segments(command)
        except Exception:
            segments = [command]
        for seg in segments:
            try:
                argv = shlex.split(seg)
            except ValueError:
                continue
            if _segment_writes_adc_via_cp_mv_tee(argv, seg):
                return "adc-file-cp-mv-tee-write"
        return None
    except Exception:
        return None


