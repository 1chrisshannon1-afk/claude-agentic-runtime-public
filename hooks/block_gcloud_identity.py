# Value spellings treated as explicitly FALSE (P3-2, round 4 fix round;
# corrected round 6, P3-1). ROUND 6 CORRECTION: this comment previously
# claimed these spellings come from gcloud's `StoreTrueFalseAction` -- that
# is WRONG for `--log-http` specifically. Verified against the installed SDK
# (574.0.0) source: `--log-http` is registered with
# `action=actions.StoreBooleanProperty(...)` (`calliope/cli.py:582-584`),
# and `StoreBooleanProperty` forces `kwargs['nargs'] = 0`
# (`calliope/actions.py:174-176`) whenever the caller (as `--log-http`'s own
# registration does) does not itself set `nargs` -- a STRICT zero-argument
# boolean flag under argparse. `--log-http=false` is therefore not merely
